#!/usr/bin/env python3
"""Replay of the d = 2, 3 resummation numbers from the shipped records (new tool, 2026-10-14). Run from code/resum_d23/.

Reads 2d/results/curves.csv, 3d/results/curves.csv and combined/cb3_gff_only.csv and checks, with a PASS/FAIL table:
  1. every quoted d = 2, 3 number owned by this package (../../results/quoted_numbers.json, package "resum_d23":
     \\RStwoDenv, \\RSthreeDenv, \\RStwoDendpoint, \\RStwoDendpointMid, \\RSthreeDcone, \\RSgffOnlyTwo, \\RSgffOnlyThree, \\RSgffDevTwo,
     \\RSgffDevThree, \\RScbThreeTwo) and the 28 resummed values of tab:num2 and tab:num3 (four d = 3 couplings lie
     between grid points: linear interpolation, whose quadratic error estimate must be 10 times smaller than the
     distance to the nearest rounding boundary);
  2. the plotted data of the figure script (2d/inputs/plot_data.json, 3d/inputs/plot_data.json: the curves) against the
     curve tables, exactly;
  3. (shipped tree only) the literature table combined/literature_mc_2d3d.csv regenerated byte for byte by a re-pointed
     copy of the verbatim combined/make_literature_table.py from the frozen extraction ../../data/inputs/literature/.
Usage: python3 public/replay_d23.py [--tree DIR] [--out FILE]
"""
import argparse, csv, json, re, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PKG = HERE.parent
RS = PKG.parent.parent
sys.path.insert(0, str(RS/'verify'))
import rsum_lib as L


def load(tree, d):
    return list(csv.DictReader((tree/d/'results'/'curves.csv').open()))


def col(rows, c):
    return [float(r[c]) for r in rows]


def at(rows, x):
    r = min(rows, key=lambda r: abs(float(r['Delta_sigma']) - x))
    assert abs(float(r['Delta_sigma']) - x) < 1e-9, (x, r['Delta_sigma'])
    return r


def quoted_numbers(tree, T):
    Q, tab = L.quoted(RS/'results'/'quoted_numbers.json')
    c2, c3 = load(tree, '2d'), load(tree, '3d')
    T.check('curve grids', len(c2) == 754 and len(c3) == 763, '%d / %d rows' % (len(c2), len(c3)), '754 / 763',
            '2d: 0.125..0.5; 3d: S = 0.518148806..0.75')
    w2 = max((float(r['curvature_core_high']) - float(r['curvature_core_low']), float(r['Delta_sigma'])) for r in c2)
    w3 = max((float(r['slope_core_high']) - float(r['slope_core_low']), float(r['Delta_sigma'])) for r in c3)
    T.quoted(Q['\\RStwoDenv'], [w2[0]], 'largest width of the 2d core band (curvature construction) over the grid (at %.4g)' % w2[1])
    T.quoted(Q['\\RSthreeDenv'], [w3[0]], 'largest width of the 3d core band (slope construction) over the grid (at %.4g)' % w3[1])
    dv = max(abs(float(r['value_CB8']) - float(r['curvature_CB8'])) for r in c2)
    dt = max(abs(float(r['tangent_CB8']) - float(r['curvature_CB8'])) for r in c2)
    T.quoted(Q['\\RStwoDendpoint'], [max(dv, dt)], '2d: largest |value-only or value+zero-slope CB8 - curvature CB8| (value %.2e, tangent %.2e)' % (dv, dt))
    mid = [(abs(float(r[k + '_CB8']) - float(r['curvature_CB8'])), float(r['Delta_sigma']), k)
           for x in (0.3, 0.35, 0.4) for r in [at(c2, x)] for k in ('tangent', 'value', 'direct')]
    em = max(mid)
    T.quoted(Q['\\RStwoDendpointMid'], [em[0]], '2d: largest |tangent, value or GFF-only CB8 - curvature CB8| at s = 1.2, 1.3, 1.4 '
             '(Delta_sigma 0.4, 0.35, 0.3; %s at %.4g)' % (em[2], em[1]))
    dc = max(max(abs(float(r['slope_SR_high']) - float(r['slope_CB8'])), abs(float(r['slope_SR_low']) - float(r['slope_CB8']))) for r in c3)
    T.quoted(Q['\\RSthreeDcone'], [dc], '3d: largest shift of the slope CB8 when c_1 spans [0.269, 0.276] (slope_SR_low/high)')
    T.quoted(Q['\\RSgffOnlyTwo'], [float(c2[0]['direct_CB8'])], '2d GFF-only CB8 (direct) at Delta_sigma = 1/8 (exact value 1)')
    T.quoted(Q['\\RSgffOnlyThree'], [float(c3[0]['direct_CB8'])], '3d GFF-only CB8 (direct) at Delta_sigma = S (bootstrap 1.4126)')
    g2 = max(abs(float(r['direct_CB8']) - float(r['curvature_CB8'])) for r in c2)
    g3 = max((abs(float(r['direct_CB8']) - float(r['slope_CB8'])), float(r['Delta_sigma'])) for r in c3)
    T.quoted(Q['\\RSgffDevTwo'], [g2], '2d: largest |GFF-only CB8 - curvature CB8| over the grid')
    T.quoted(Q['\\RSgffDevThree'], [g3[0]], '3d: largest |GFF-only CB8 - slope CB8| over the grid (at %.4g)' % g3[1])
    cb3 = [r for r in csv.DictReader((tree/'combined'/'cb3_gff_only.csv').open()) if r['d'] == '2']
    ok = len(cb3) == len(c2) and all(abs(float(a['Delta_sigma']) - float(b['Delta_sigma'])) < 1e-12 for a, b in zip(cb3, c2))
    T.check('CB3 grid = 2d grid', ok, '%d rows' % len(cb3), '754 rows on the curve grid', 'combined/cb3_gff_only.csv, d = 2')
    d3 = max(abs(float(a['CB3_direct']) - float(b['curvature_CB8'])) for a, b in zip(cb3, c2))
    T.quoted(Q['\\RScbThreeTwo'], [d3], '2d: largest |CB3 (GFF only, C_0..C_3) - curvature CB8| over the grid')
    for row in [t for t in tab if t['package'] == 'resum_d23']:
        rows, base = (c2, 'curvature') if row['d'] == 2 else (c3, 'slope')
        v, err, how = L.interpolate(col(rows, 'Delta_sigma'), col(rows, base + '_CB8'), float(row['Delta_sigma']))
        ok, margin = L.cell(v, row['text'], err)
        T.check('%s d=%d %s Resummed' % (row['table'], row['d'], row['Delta_sigma']), ok,
                '%.8f' % v + ('' if err == 0 else ' (interp. error %.1e, margin %.1e)' % (err, margin)), row['text'],
                '%s CB8, %s; rounded like the table' % (base, how))
    return c2, c3


def plotted(tree, c2, c3, T):
    for d, rows in (('2d', c2), ('3d', c3)):
        P = json.loads((tree/d/'inputs'/'plot_data.json').read_text())
        pc = P['curves']
        same = lambda pv, rv: (pv is None or pv == '') if rv == '' else (pv is not None and float(pv) == float(rv))
        ok = len(pc) == len(rows) and all(all(same(p.get(k), r[k]) for k in r) for p, r in zip(pc, rows))
        T.check('%s plot data = curve table' % d, ok, '%d points' % len(pc), 'identical floats, all columns (blank = null)',
                '%s/inputs/plot_data.json curves vs %s/results/curves.csv' % (d, d))


def regenerate_literature(work, T):
    """The script records each source as a path relative to its ROOT, so the frozen extraction is laid out under
    <work>/root/ at the relative path its SRC line names; only the ROOT and OUT lines change."""
    import shutil
    src = PKG/'combined'/'make_literature_table.py'
    root = (work/'root').resolve()
    shutil.rmtree(root, ignore_errors=True)
    rel = re.search(r'^SRC = ROOT / "([^"]+)"', src.read_text(), flags=re.M).group(1)
    dst = root/rel
    dst.mkdir(parents=True)
    for f in ('lit_2d.csv', 'lit_3d.csv'):
        shutil.copy2(RS/'data'/'inputs'/'literature'/f, dst/f)
    out = (work/'literature_mc_2d3d.csv').resolve()
    t = src.read_text()
    for pat, new in ((r'^ROOT = Path\(.*\)$', 'ROOT = Path(%r)' % str(root)), (r'^OUT = ROOT / .*$', 'OUT = Path(%r)' % str(out))):
        t, n = re.subn(pat, lambda m: new, t, flags=re.M)   # the path lines may carry placeholders in the published copy
        assert n == 1, pat
    (work/'make_literature_table.py').write_text(t)
    r = subprocess.run([sys.executable, '-B', str(work/'make_literature_table.py')], capture_output=True, text=True)
    ok = r.returncode == 0 and out.read_bytes() == (PKG/'combined'/'literature_mc_2d3d.csv').read_bytes()
    T.check('literature_mc_2d3d.csv regenerated', ok, 'exit %d, %s' % (r.returncode, 'identical' if ok else 'differs'),
            'byte-identical', 'combined/make_literature_table.py (verbatim; ROOT and OUT re-pointed; frozen extraction in data/inputs/literature)')
    if not ok:
        print(r.stdout[-2000:], r.stderr[-2000:])


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--tree', default=str(PKG))
    ap.add_argument('--work', default=str(PKG/'.work'))
    ap.add_argument('--out', default=None)
    a = ap.parse_args(argv)
    tree, work = Path(a.tree).resolve(), Path(a.work).resolve()
    T = L.Table('resum_d23 replay (%s)' % ('shipped records' if tree == PKG else 'rerun copy'))
    c2, c3 = quoted_numbers(tree, T)
    plotted(tree, c2, c3, T)
    if tree == PKG:
        regenerate_literature(work/'literature', T)
    return T.report(a.out or work/'replay_d23.txt')


if __name__ == '__main__':
    sys.exit(main())
