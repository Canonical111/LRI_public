#!/usr/bin/env python3
"""The comparison of HT, NRG and MC with each other and with the resummed curves (new tool, 2026-10-14; paper Sec.
"Comparison", the \\CMP* macros). Run from code/comparison/.

Inputs (all shipped): the d = 1 comparison table written by the resummation chain
(../resum_d1/update_2026-10-13/C8_1_ext/pipeline_K8/results/comparison_points_K.csv: every HT, NRG and MC value with the
K = 8 and K = 4 curves evaluated exactly at its coupling), the curve tables (../resum_d1/.../curve_K.csv,
../resum_d23/{2d,3d}/results/curves.csv), and frozen copies of the other folders' records in ../../data/inputs/ (NRG
ds13_final.json; HT dens_v1_extrapolation.json, model_dependence.json, HT_2d largest_N.csv; MC final_table.csv,
largest_pairs_rows.tex, evaluation_2d.json, evaluation_3d.json), and the d = 3 HT records at N = 20
(../resum_d23/3d/inputs/ht_l20/, listed in ../resum_d23/3d/inputs/plot_data.json).
Checks, in order:
  1. the values inside comparison_points_K.csv are the records: NRG = ds13_final.json (Delta_E, total, status), HT =
     dens_v1_extrapolation.json (D_inf, half-spread) at Delta_sigma >= 0.075, MC = final_table.csv (Delta_epsilon,
     sigma_stat, sigma_sys, decision); the 3d MC point used by the figure (../resum_d23/3d/inputs/mc_accepted.json) = the
     quoted s = 1.6 value of evaluation_3d.json;
  2. the 12 \\CMP* macros (../../results/quoted_numbers.json), each with its rule in the table;
  3. INFO: the d = 2 sentence without a macro ("finite-cutoff HT lies above the curve by up to about 1% at
     0.175 <= Delta_sigma <= 0.3"), from HT_2d largest_N.csv against the curvature CB8;
  4. the cells of the paper's tables tab:num2 and tab:num3 taken from these records: HT at the largest cutoff (d = 2:
     HT_2d largest_N.csv, N = 24, or N = 22 in brackets; d = 3: the N = 20 records in ../resum_d23/3d/inputs/ht_l20/), rounded
     like the table, and the d = 2 MC column (evaluation_2d.json, Binder exponent from L = 512 -> 1024, PDG rounding);
  5. the three comparison tables in ../../results/comparison/ regenerated byte for byte (--write rewrites them).
Usage: python3 public/compare.py [--write] [--work DIR]
"""
import argparse, csv, io, json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PKG = HERE.parent
RS = PKG.parent.parent
CODE = PKG.parent
sys.path.insert(0, str(RS/'verify'))
import rsum_lib as L

DATA = RS/'data'/'inputs'
OUT = RS/'results'/'comparison'
CP = CODE/'resum_d1'/'update_2026-10-13'/'C8_1_ext'/'pipeline_K8'/'results'/'comparison_points_K.csv'
CURVE1 = CODE/'resum_d1'/'update_2026-10-13'/'C8_1_ext'/'pipeline_K8'/'results'/'curve_K.csv'


def grid(path, x, col, required=True):
    """Value of a curve column at a grid point (no interpolation); None if x is not a grid point and not required."""
    r = min(csv.DictReader(path.open()), key=lambda r: abs(float(r['Delta_sigma']) - x))
    if abs(float(r['Delta_sigma']) - x) >= 1e-9:
        assert not required, (path, x)
        return None, None
    return float(r[col]), r


def csv_text(rows):
    s = io.StringIO()
    w = csv.DictWriter(s, fieldnames=list(rows[0]), lineterminator='\n'); w.writeheader(); w.writerows(rows)
    return s.getvalue()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true', help='rewrite ../../results/comparison/*.csv (maintenance)')
    ap.add_argument('--work', default=str(PKG/'.work'))
    a = ap.parse_args()
    Q, tab = L.quoted(RS/'results'/'quoted_numbers.json')
    T = L.Table('comparison replay')
    pts = list(csv.DictReader(CP.open()))
    by = lambda m: [r for r in pts if r['method'] == m]

    # 1. the values in the comparison table are the records
    nrg = {round(r['ds'], 6): r for r in json.loads((DATA/'NRG'/'ds13_final.json').read_text())}
    ok = len(by('NRG')) == 13
    for r in by('NRG'):
        n = nrg[round(float(r['x']), 6)]
        ok &= float(r['y']) == n['Delta_E'] and (r['status'] == 'final') == (n['status'] == 'final')
        ok &= (float(r['error']) == n['total']) if r['status'] == 'final' else (r['error'] == '' and n['total'] is None)
    T.check('NRG values = record', ok, '13 rows', 'identical', 'comparison_points_K.csv vs data/inputs/NRG/ds13_final.json')
    ht = {round(r['delta'], 6): r['fit'] for r in json.loads((DATA/'HT'/'HT_1d'/'dens_v1_extrapolation.json').read_text())}
    rows = [r for r in by('HT') if float(r['x']) >= 0.075 - 1e-12]
    ok = len(rows) == 9 and all(float(r['y']) == ht[round(float(r['x']), 6)]['D_inf'] and
                                float(r['error']) == ht[round(float(r['x']), 6)]['spread_half'] for r in rows)
    T.check('HT values = record', ok, '%d rows' % len(rows), 'identical', 'final and one-sided HT vs data/inputs/HT/HT_1d/dens_v1_extrapolation.json')
    mc = {round(float(r['Delta_sigma']), 7): r for r in csv.DictReader((DATA/'MC'/'1d'/'final_table.csv').open())}
    ok = len(by('MC')) == 17
    for r in by('MC'):
        m = mc[round(float(r['x']), 7)]
        ok &= float(r['y']) == float(m['Delta_epsilon']) and r['status'] == m['decision']
        ok &= float(r['stat']) == float(m['sigma_stat'])
        ok &= (float(r['error']) == float(m['sigma_sys'])) if m['sigma_sys'] not in ('', '—') else r['error'] == ''
    T.check('MC values = record', ok, '17 rows', 'identical', 'comparison_points_K.csv vs data/inputs/MC/1d/final_table.csv')
    e3 = json.loads((DATA/'MC'/'3d'/'evaluation_3d.json').read_text())['points']
    acc = json.loads((CODE/'resum_d23'/'3d'/'inputs'/'mc_accepted.json').read_text())
    q = e3['1.6']['quoted']
    ok = (len(acc) == 1 and acc[0]['s'] == 1.6 and acc[0]['decision'] == e3['1.6']['decision'] and
          all(acc[0][k] == q[k] for k in ('Delta_epsilon', 'sigma_stat', 'sigma_sys')))
    T.check('3d MC point = record', ok, '%r' % acc[0]['Delta_epsilon'], '%r (s = 1.6, %s)' % (q['Delta_epsilon'], e3['1.6']['decision']),
            '../resum_d23/3d/inputs/mc_accepted.json (value, stat, sys, decision) vs evaluation_3d.json quoted')

    # 2. the macros
    final = lambda m, st: [r for r in by(m) if r['status'] in st]
    res = lambda r: float(r['method_minus_K8'])
    hf = final('HT', ('final',))
    T.quoted(Q['\\CMPhtCB'], [max(abs(res(r)) for r in hf)], 'largest |HT - CB8 (K=8)| over the %d final HT values (0.1 <= Ds <= 0.249)' % len(hf))
    ho = final('HT', ('one_sided',))
    T.quoted(Q['\\CMPhtCBos'], [abs(res(ho[0]))], '|HT - CB8| at the one-sided HT point (Ds = %s)' % ho[0]['x'])
    nf = final('NRG', ('final',))
    T.quoted(Q['\\CMPnrgCB'], [max(abs(res(r)) for r in nf)], 'largest |NRG - CB8| over the %d converged NRG values' % len(nf))
    T.check('NRG below CB8', all(res(r) < 0 for r in nf), '%d of %d below' % (sum(res(r) < 0 for r in nf), len(nf)), 'all',
            '"all of which lie below it"')
    ma = [r for r in by('MC') if r['status'].startswith('ACCEPTED')]
    T.quoted(Q['\\CMPmcCB'], [max(abs(res(r)) for r in ma)], 'largest |MC - CB8| over the %d accepted MC values' % len(ma))
    nrgf = {round(float(r['x']), 7): float(r['y']) for r in nf}
    rel = [(200*abs(float(r['y']) - nrgf[round(float(r['x']), 7)])/(float(r['y']) + nrgf[round(float(r['x']), 7)]), r['x'])
           for r in ma if round(float(r['x']), 7) in nrgf]
    mx = max(rel)
    T.quoted(Q['\\CMPmcNrgRel'], [mx[0]], 'largest |MC - NRG| / mean, in %%, over accepted MC with converged NRG (%d couplings; at %s)' % (len(rel), mx[1]))
    h1 = [r for r in by('HT') if abs(float(r['x']) - 0.1) < 1e-12][0]
    m1 = [r for r in ma if abs(float(r['x']) - 0.1) < 1e-12][0]
    T.quoted(Q['\\CMPhtMcRel'], [200*abs(float(h1['y']) - float(m1['y']))/(float(h1['y']) + float(m1['y']))], '|HT - MC| / mean at Ds = 0.1, in %')
    lp = {}
    for line in (DATA/'MC'/'1d'/'largest_pairs_rows.tex').read_text().splitlines():
        m = re.match(r'\s*([0-9.]+)\s*&.*&\s*([0-9]+k--[0-9]+k):\s*([0-9.]+)\(', line)
        if m:
            lp[round(float(m.group(1)), 7)] = (float(m.group(3)), m.group(2))
    gauss = []
    for x in (0.2125, 0.225, 0.2375):
        row = mc[round(x, 7)]
        if row['Delta_epsilon'] not in ('', '—'):
            v, how = float(row['Delta_epsilon']), 'fit (%s)' % row['decision']
        else:
            v, how = lp[round(x, 7)][0], 'largest pair %s (%s)' % (lp[round(x, 7)][1], row['decision'])
        cb = grid(CURVE1, x, 'endpoint_v_K8_L8')[0]
        gauss.append({'Delta_sigma': x, 'MC_value': v, 'MC_kind': how, 'CB8_K8': repr(cb), 'MC_minus_CB8': repr(v - cb)})
    d = [abs(float(g['MC_minus_CB8'])) for g in gauss]
    T.quoted(Q['\\CMPmcGauss'], [min(d), max(d)], 'MC finite-size values below CB8 at 0.2125 <= Ds <= 0.2375 (min, max of |diff|; all below: %s)'
             % all(float(g['MC_minus_CB8']) < 0 for g in gauss))
    e2 = json.loads((DATA/'MC'/'2d'/'evaluation_2d.json').read_text())['points']
    C2 = RS/'code'/'resum_d23'/'2d'/'results'/'curves.csv'
    C3 = RS/'code'/'resum_d23'/'3d'/'results'/'curves.csv'
    two = []
    for s in sorted(e2, key=float):
        p = [x for x in e2[s]['largest_pairs'] if x['pair'] == '512->1024'][0]
        cb, r = grid(C2, (2 - float(s))/2, 'curvature_CB8')
        two.append({'s': s, 'Delta_sigma': repr((2 - float(s))/2), 'pair': p['pair'], 'Delta_eff_U4': repr(p['Delta_eff_U4']),
                    'sigma_U4': repr(p['sigma_U4']), 'decision': e2[s]['decision'], 'curvature_CB8': repr(cb),
                    'core_low': r['curvature_core_low'], 'core_high': r['curvature_core_high'], 'U4_minus_CB8': repr(p['Delta_eff_U4'] - cb)})
    mid = [abs(float(t['U4_minus_CB8'])) for t in two if t['s'] in ('1.2', '1.3', '1.4')]
    T.quoted(Q['\\CMPtwoUfour'], [max(mid)], 'd=2: largest |Deff(U4, 512->1024) - CB8| at s = 1.2, 1.3, 1.4')
    ends = [float(t['U4_minus_CB8']) for t in two if t['s'] in ('1.05', '1.1', '1.5', '1.6', '1.7')]
    T.quoted(Q['\\CMPtwoUfourEnds'], [min(abs(v) for v in ends), max(abs(v) for v in ends)],
             'd=2: |Deff(U4) - CB8| at s = 1.05, 1.1 and 1.5, 1.6, 1.7 (min, max; all short of CB8: %s)' % all(v < 0 for v in ends))
    three = []
    for s in sorted(e3, key=float):
        qq = e3[s].get('quoted')
        cb = grid(C3, (3 - float(s))/2, 'slope_CB8', required=False)[0]       # s = 1.95 (0.525) is not a grid point
        three.append({'s': s, 'Delta_sigma': repr((3 - float(s))/2), 'decision': e3[s]['decision'],
                      'Delta_epsilon': repr(qq['Delta_epsilon']) if qq else '', 'sigma_stat': repr(qq['sigma_stat']) if qq else '',
                      'sigma_sys': repr(qq['sigma_sys']) if qq else '', 'slope_CB8': repr(cb) if cb is not None else '',
                      'minus_CB8': repr(qq['Delta_epsilon'] - cb) if qq and cb is not None else ''})
    t16 = [t for t in three if t['s'] == '1.6'][0]
    T.quoted(Q['\\CMPthreeMC'], [float(t16['minus_CB8'])], 'd=3: accepted MC at s = 1.6 (%s) minus slope CB8' % t16['decision'])
    sr = [float(t['minus_CB8']) for t in three if t['s'] in ('1.7', '1.85', '1.9')]
    T.quoted(Q['\\CMPthreeMCsr'], [min(sr), max(sr)], 'd=3: non-accepted extrapolations at s = 1.7, 1.85, 1.9 minus CB8 (min, max)')
    k = list(csv.DictReader(CURVE1.open()))
    dk = max((abs(float(r['endpoint_v_K4_L8']) - float(r['endpoint_v_K8_L8'])), r['Delta_sigma']) for r in k)
    T.quoted(Q['\\CMPkfourKeight'], [dk[0]], 'largest |CB8(K=4) - CB8(K=8)| over the 1004-point grid (at %s)' % dk[1])

    # 3. INFO: d = 2 finite-cutoff HT above the curve
    htrows = []
    for r in csv.DictReader((DATA/'HT'/'HT_2d'/'largest_N.csv').open()):
        x = float(r['Delta_sigma'])
        cb = grid(C2, x, 'curvature_CB8')[0]
        htrows.append({'Delta_sigma': r['Delta_sigma'], 'N': r['N'], 'HT_Delta_E': r['Delta_E'], 'curvature_CB8': repr(cb),
                       'HT_minus_CB8': repr(float(r['Delta_E']) - cb), 'relative_percent': repr(100*(float(r['Delta_E']) - cb)/cb)})
    win = [float(h['relative_percent']) for h in htrows if 0.175 - 1e-9 <= float(h['Delta_sigma']) <= 0.3 + 1e-9]
    T.add('d=2 HT above the curve', 'INFO', 'max %.2f%%, min %.2f%% over %d points' % (max(win), min(win), len(win)), '"up to about 1%"',
          '100 (HT_largest_N - curvature CB8)/CB8 at 0.175 <= Ds <= 0.3 (no macro; reading: the maximum rounds to 1%)')

    # 4. the paper's tables tab:num2 and tab:num3: the HT column (d = 2, 3) and the MC column (d = 2)
    ht2 = {round(float(r['Delta_sigma']), 7): r for r in csv.DictReader((DATA/'HT'/'HT_2d'/'largest_N.csv').open())}
    l20 = {round(h['Delta_sigma'], 7): h for h in json.loads((CODE/'resum_d23'/'3d'/'inputs'/'plot_data.json').read_text())['ht_l20']}
    cells = [t for t in tab if t['package'] == 'comparison']
    for row in cells:
        x, name = round(float(row['Delta_sigma']), 7), '%s d=%d %s %s' % (row['table'], row['d'], row['Delta_sigma'], row['column'])
        if row['column'] == 'HT' and row['d'] == 2:
            r = ht2[x]
            v, br = float(r['Delta_E']), r['N'] != '24'
            ok = L.cell(v, row['text'])[0] and row['text'].startswith('[') == br and r['N'] in ('22', '24')
            T.check(name, ok, '%.8f (N = %s)' % (v, r['N']), row['text'],
                    'data/inputs/HT/HT_2d/largest_N.csv Delta_E at the largest cutoff; N = 24, or N = 22 in brackets')
        elif row['column'] == 'HT':
            h = l20[x]
            rec = json.loads((CODE/'resum_d23'/'3d'/'inputs'/'ht_l20'/h['source']).read_text())
            v = rec['Delta_thermal']
            ok = (L.cell(v, row['text'])[0] and v == h['HT_L20'] and rec['accepted'] is True and h['source'].endswith('window_L20.json')
                  and not row['text'].startswith('['))
            T.check(name, ok, '%.8f' % v, row['text'] + (' (%s)' % row['macro'] if 'macro' in row else ''),
                    'Delta_thermal of 3d/inputs/ht_l20/%s (N = 20, accepted) = plot_data.json HT_L20' % h['source'])
        else:
            t2 = [t for t in two if abs(float(t['Delta_sigma']) - float(row['Delta_sigma'])) < 1e-9]
            v, e = float(t2[0]['Delta_eff_U4']), float(t2[0]['sigma_U4'])
            T.check(name, len(t2) == 1 and L.pdg(v, e) == row['text'], '%s (%.6f +- %.6f)' % (L.pdg(v, e), v, e), row['text'],
                    'data/inputs/MC/2d/evaluation_2d.json: Delta_eff(U4), pair 512->1024, with its bootstrap error, PDG rounding')
    T.check('tab:num2/3 cells from this package', len(cells) == 36, '%d' % len(cells), '36 (13 + 15 HT, 8 MC)', 'quoted_numbers.json tab_num')

    # 5. comparison tables
    tables = {'mc_1d_gaussian_end.csv': gauss, 'mc_2d3d_vs_CB8.csv': [dict(t, d=2) for t in two] + [dict(t, d=3) for t in three],
              'ht_2d_largest_N_vs_CB8.csv': htrows}
    tables['mc_2d3d_vs_CB8.csv'] = [{k: t.get(k, '') for k in ('d', 's', 'Delta_sigma', 'decision', 'pair', 'Delta_eff_U4', 'sigma_U4',
                                                                  'curvature_CB8', 'core_low', 'core_high', 'U4_minus_CB8', 'Delta_epsilon',
                                                                  'sigma_stat', 'sigma_sys', 'slope_CB8', 'minus_CB8')}
                                    for t in tables['mc_2d3d_vs_CB8.csv']]
    for name, rows in tables.items():
        text = csv_text(rows)
        if a.write:
            OUT.mkdir(parents=True, exist_ok=True); (OUT/name).write_text(text)
        ok = (OUT/name).exists() and (OUT/name).read_text() == text
        T.check('results/comparison/' + name, ok, '%d rows' % len(rows), 'identical to the shipped table', 'regenerated from the records')
    return T.report(Path(a.work)/'replay_comparison.txt')


if __name__ == '__main__':
    sys.exit(main())
