#!/usr/bin/env python3
"""A-RPL-5: the precision policy per tier at L7 and L8 against 450 digits (tests/forced_tiers.cpp, built with the
Makefile's flags and -DC8_USE_GMP, so every point also gets decimal300).

Sample, per sector: 200 L7 kernels x 256 points and 400 L8 kernels x 64 points (the 50 and 100 heaviest plus random
ones), points generated by sample() from a fixed net exactly as the worker does. Every point gets every tier and an
independent 450-digit value. A sector needs at least 10^4 points accepted in binary128 and 10^3 MP-promoted points;
otherwise the points per kernel double (the new points [P, 2P) are added) until it does (at most --max-doublings).
Gates: (a) accepted in long double |f - f450| <= 1e-15 err_ld, accepted in binary128 |f - f450| <= 1e-29 err_q (so the
relative error after the acceptance tests is <= 1e-6); (b) every gmp350 value within 1e-280 (1 + err), and every
decimal300 value of an MP-promoted point; (c) the tier decisions equal evaluate()'s. The per-tier distributions are
reported. Records only to --output.
Y1 (Stage-6 fix round 2): the tool is bound to the gmp worker it speaks for (--worker, default bin/c8d2_gmp) through
that worker's build record (tools/build_record.py bound_tool_command): the same make flags and compiler, the worker's
GMP_PREFIX words (-I<prefix>/include, -L/-rpath <prefix>/lib) and gmp.h, and after linking the tool must resolve the
libgmp whose sha256 the record names, as the worker itself must here. Anything else is refused before a point is
evaluated (exit with the reason); the record carries the binding (gmp_binding).
Z1 (Stage-6 fix round 3): the tool is also bound to the worker's code. It is compiled from a read-only snapshot of src/
and tests/forced_tiers.cpp, in which the worker is first rebuilt with its build record's command and must come out
byte for byte (tools/build_record.py source_snapshot, reproduce_worker): a stale worker (src/ edited since its build),
an older --worker with the same flags and GMP, or a Boost changed through the include environment is refused before
a point is evaluated; gmp_binding.source_binding records the snapshot and the reproduction.
Z2 (Stage-6 fix round 3): "status":"passed" (A-RPL-5 acceptance evidence) only with the complete coverage (coverage():
scale 1, both sectors, per sector the binary128 and MP quotas, per (sector, L) the prescribed graphs and points per
graph, the tool bound to the worker's sources); a run with --scale or a --sectors subset is labelled a development run
and lists what it lacks in "coverage". A consumer checks a record with `forced_tiers.py --check RECORD` (exit 0 only
for a passed record whose recomputed coverage is complete) or coverage(record).
"""
from __future__ import annotations
from pathlib import Path
import argparse,json,os,subprocess,sys,tempfile,time
from decimal import Decimal as D
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'tools'));sys.path.insert(0,str(ROOT/'tests'))
from common import dump,environment_record
from build_record import BindingRefused,bound_tool_command,verify_tool
from validate import stage,heavy_and_random,make_net,run

SAMPLE={7:(50,150,256),8:(100,300,64)}   # L: (heaviest, random, points per kernel)
PRESCRIBED=dict(SAMPLE)                   # A-RPL-5's sample (Z2: --scale changes SAMPLE, never this)
NEED_QUAD,NEED_MP=10_000,1_000
SECTORS=('free','power')
COUNTERS=('decision_mismatch','ld_violations','quad_violations','mp_violations','decimal300_violations')

def coverage(rec:dict,source_binding:bool=True)->dict:
    """Z2: whether a forced_tiers record is A-RPL-5 acceptance evidence. complete only with: scale 1 and the prescribed
    sample; both sectors, each once; per sector at least NEED_QUAD binary128-accepted and NEED_MP MP-promoted points
    (recounted from the per-L levels); per (sector, L) the prescribed number of graphs and SAMPLE's points per graph x
    2^doublings, no violation counter; and the tool bound to the worker's code (gmp_binding.source_binding: the worker
    reproduced byte for byte from the snapshot the tool was compiled from, Z1). {'complete': bool, 'why': [...],
    'source_binding_checked': bool}. source_binding=False skips only the Z1 condition: for the summaries of records made
    before fix round 3 (benchmarks/*/scripts), which predate the source binding; acceptance (--check) always checks it."""
    why=[];rec=rec if isinstance(rec,dict)else{}
    if rec.get('scale')!=1:why.append(f'scale {rec.get("scale")!r}, not 1')
    want={str(L):{'heaviest':h,'random':r,'points':n}for L,(h,r,n)in PRESCRIBED.items()}
    if {str(k):v for k,v in (rec.get('sample')or{}).items()}!=want:why.append(f'sample {rec.get("sample")!r}, not the prescribed {want}')
    secs=rec.get('sectors')if isinstance(rec.get('sectors'),dict)else{}
    if sorted(secs)!=sorted(SECTORS):why.append(f'sectors {sorted(secs)}, not both of {list(SECTORS)}')
    for s in SECTORS:
        x=secs.get(s)
        if not isinstance(x,dict):continue
        byL={str(k):v for k,v in (x.get('by_L')or{}).items()};dbl=x.get('doublings');quad=mp=0
        for L,(h,r,n)in PRESCRIBED.items():
            y=byL.get(str(L))
            if not isinstance(y,dict):why.append(f'{s} L{L}: missing');continue
            if y.get('graphs')!=h+r:why.append(f'{s} L{L}: {y.get("graphs")!r} graphs, not {h + r}')
            if not (isinstance(dbl,int)and dbl>=0 and y.get('points_per_graph')==n<<dbl):why.append(f'{s} L{L}: {y.get("points_per_graph")!r} points per graph, not {n} x 2^{dbl!r}')
            bad={k:y.get(k)for k in COUNTERS if y.get(k)!=0}
            if bad:why.append(f'{s} L{L}: violation counters {bad}')
            lev=y.get('level')or[0,0,0];quad+=int(lev[1]);mp+=int(lev[2])
        if quad<NEED_QUAD or mp<NEED_MP:why.append(f'{s}: {quad} binary128-accepted and {mp} MP points, below {NEED_QUAD} and {NEED_MP}')
    sb=((rec.get('gmp_binding')or{}).get('source_binding')or{})
    if source_binding and not ((sb.get('reproduction')or{}).get('reproduced')is True and (sb.get('reproduction')or{}).get('sha256')==(rec.get('gmp_binding')or{}).get('worker_sha256')):
        why.append('the tool is not bound to the worker\'s sources (gmp_binding.source_binding: no byte-identical reproduction of the worker, Z1)')
    return {'complete':not why,'why':why,'source_binding_checked':bool(source_binding)}

def check(path:Path)->int:
    """--check: 0 for a record that says "passed" and whose recomputed coverage is complete, 1 otherwise."""
    rec=json.loads(Path(path).read_text());cov=coverage(rec);good=rec.get('status')=='passed'and cov['complete']
    print(json.dumps({'record':str(path),'status':rec.get('status'),'acceptance':good,'coverage':cov},indent=1));return 0 if good else 1

def merge(a:dict,b:dict)->dict:
    if not a:return b
    out=dict(a)
    for k in ('points','nonmoderate','nondirect','decision_mismatch','ld_violations','quad_violations','mp_violations','decimal300_violations'):out[k]=a[k]+b[k]
    out['level']=[x+y for x,y in zip(a['level'],b['level'])]
    for k in [k for k in a if k.startswith('max_')]:out[k]=str(max(D(a[k]),D(b[k])))
    for k in [k for k in a if k.startswith('hist_')]:
        h=dict(a[k])
        for kk,v in b[k].items():h[kk]=h.get(kk,0)+v
        out[k]=h
    out['first_violations']=(a['first_violations']+b['first_violations'])[:20];out['end']=b['end']
    return out

def main():
    ap=argparse.ArgumentParser(description=__doc__,formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--output',type=Path)
    ap.add_argument('--threads',type=int,default=len(os.sched_getaffinity(0))if hasattr(os,'sched_getaffinity')else(os.cpu_count()or 1))
    ap.add_argument('--worker',type=Path,default=ROOT/'bin/c8d2_gmp',help='the gmp worker the tool is bound to (Y1: its build record\'s flags, compiler, GMP_PREFIX, gmp.h and libgmp)')
    ap.add_argument('--max-doublings',type=int,default=4);ap.add_argument('--sectors',nargs='+',default=list(SECTORS),choices=SECTORS,
                                                                        help='development only: a subset (the record is then no acceptance evidence, Z2)')
    ap.add_argument('--scale',type=float,default=1.0,help='development only: scale the kernel counts (the record says so; the gate needs 1)')
    ap.add_argument('--check',type=Path,metavar='RECORD',help='check an existing record: exit 0 only for acceptance evidence (Z2)')
    a=ap.parse_args()
    if a.check:sys.exit(check(a.check))
    a.sectors=list(dict.fromkeys(a.sectors))   # a sector named twice runs once
    if a.scale!=1:
        for L,(h,r,n) in list(SAMPLE.items()):SAMPLE[L]=(max(1,round(h*a.scale)),max(1,round(r*a.scale)),n)
    if a.output and a.output.exists():raise SystemExit(f'{a.output} exists')
    t0=time.time();sectors={}
    with tempfile.TemporaryDirectory(prefix='c8d2_tiers_')as td:
        td=Path(td);tool=td/'forced_tiers'
        try:cmd,binding=bound_tool_command([ROOT/'tests/forced_tiers.cpp'],tool,a.worker,'gmp',defines=['C8_USE_GMP'],libs=('-lquadmath','-lgmp'))
        except BindingRefused as e:raise SystemExit(f'forced_tiers: {e}')
        subprocess.run(cmd,check=True)
        try:verify_tool(tool,binding)
        except BindingRefused as e:raise SystemExit(f'forced_tiers: {e}')
        for sector in a.sectors:
            per={};points={L:SAMPLE[L][2]for L in SAMPLE};begin={L:0 for L in SAMPLE};lists={}
            for L,(heavy,rand,_) in SAMPLE.items():
                ids=heavy_and_random(sector,L,heavy,rand,40417+L+(9 if sector=='power'else 0));root=stage(td/sector,sector,L,ids)
                lists[L]=td/f'{sector}_L{L}.list';lists[L].write_text(''.join(f'{root}/L{L}/G{g}.txt\n'for g in ids))
                net=td/f'{sector}_L{L}.bin';make_net(net,1+1,4*L-1,60,30011+L+(9 if sector=='power'else 0),SAMPLE[L][2]<<a.max_doublings)
                per[L]={'graphs':ids,'net':net,'result':{}}
            rounds=0
            while True:
                for L in SAMPLE:
                    s=time.time();out=run([tool,L,lists[L],per[L]['net'],begin[L],points[L],7011,a.threads],threads=a.threads).stdout  # R1: the controlled OpenMP environment
                    per[L]['result']=merge(per[L]['result'],json.loads(out));print(f'{sector} L{L} points [{begin[L]},{points[L]}) in {time.time()-s:.0f} s',flush=True)
                quad=sum(per[L]['result']['level'][1]for L in SAMPLE);mp=sum(per[L]['result']['level'][2]for L in SAMPLE)
                if quad>=NEED_QUAD and mp>=NEED_MP:break
                if a.scale!=1:break
                if rounds>=a.max_doublings:raise AssertionError(f'{sector}: {quad} binary128-accepted and {mp} MP points after {rounds} doublings (need {NEED_QUAD} and {NEED_MP})')
                rounds+=1
                for L in SAMPLE:begin[L]=points[L];points[L]*=2
            for L in SAMPLE:
                r=per[L]['result']
                bad={k:r[k]for k in('decision_mismatch','ld_violations','quad_violations','mp_violations','decimal300_violations')if r[k]}
                if bad:raise AssertionError(f'{sector} L{L}: {bad}; first: {r["first_violations"][:5]}')
            sectors[sector]={'doublings':rounds,'binary128_accepted':quad,'mp_promoted':mp,
                             'by_L':{L:{'graphs':len(per[L]['graphs']),'points_per_graph':points[L],**per[L]['result']}for L in SAMPLE}}
    rec={'status':None,'test':'forced_tiers','scale':a.scale,'sample':{L:{'heaviest':h,'random':r,'points':n}for L,(h,r,n)in SAMPLE.items()},
         'sectors':sectors,'tool_command':cmd,'gmp_binding':binding,'need':{'binary128_accepted':NEED_QUAD,'mp_promoted':NEED_MP},
         'gates':{'a':'accepted ld: |f-f450| <= 1e-15 err_ld; accepted binary128: |f-f450| <= 1e-29 err_q','b':'every gmp350 value, and the decimal300 value of every MP-promoted point: |f-f450|/(1+err450) <= 1e-280',
                  'c':'decisions recomputed from the forced values == evaluate() level'},'wall_seconds':round(time.time()-t0,1),'environment':environment_record()}
    rec['coverage']=coverage(json.loads(json.dumps(rec,default=str)))  # Z2: judged on the record as written (string keys)
    rec['status']='passed'if rec['coverage']['complete']else'development run ('+'; '.join(rec['coverage']['why'])[:500]+')'
    if a.output:dump(a.output,rec)
    print(json.dumps({k:v for k,v in rec.items()if k!='environment'},default=str)[:6000])

if __name__=='__main__':main()
