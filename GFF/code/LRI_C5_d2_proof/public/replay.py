#!/usr/bin/env python3
"""Test and replay of LRI_C5_d2_proof: the machine checks and numerical checks of the proofs of L2 and K2 (note Sections
17.2, 18.6, 18.7; HEAD fa71533).

Run from the package folder (GFF/code/LRI_C5_d2_proof) as `make -f public.mk test` (part A only) or
`make -f public.mk replay` (parts A to C). Every shipped script runs unchanged in a work copy under public/out/work/,
with the hard-coded research-tree prefix mapped to GFF/code (public/cf2common.py).

A. Exact machine checks cited by the note (sympy). Their output must equal the shipped output.
   - L2_singlesums/verify_symbolic.py (note l.4899): 31 PASS, report byte-identical.
   - K2_selberg/region_sum_matrix.py (l.5295): the 144-term phase sum reduces to 4 s^2 (I3^2 + I4^2).
   - K2_selberg/laurent_K2_sympy.py (l.5390): K2 - (32 G^2 - 28 zeta3 log2) = 0.
   - drafter/check_algebra.py: the C5(2) algebra, the L2 collapse, the twelve cells and the K2 Laurent extraction;
     ALL ZERO.
B. Numerical checks re-run from shipped inputs.
   - L2_singlesums/check_vs_C62d_dps70.py (note l.5143-5144, "to 3x10^-70"): elliptic M, N by AGM quadrature at 75 digits
     against the 70-digit single sums of ../LRI_C5_d2_simplify/confirm_dps70.json. Output byte-identical to the shipped
     JSON.
   - public/spec_analyze_scaled.py (note l.5181-5182, "2x10^-70"): the reviewer's tail fit of the stored spectral moments
     review_L2_structural_numerics_r0/spec_<x>.json, with column scaling. The shipped spec_analyze.py stops with a singular
     matrix (see the header of spec_analyze_scaled.py).
   - pi^2[F(3/10)^2 + F(7/10)^2] (note l.5453) by mpmath 3F2 at 30 digits.
C. Recorded check outputs behind the other quoted check numbers. These runs need Mathematica or cluster hours; their
   outputs are read and compared at the printed digits.
   - l.5145-5146 "to 10^-82": review_L2_singlesums_numerics_r0/s3.log.
   - l.5146-5148 "about 35 digits": drafter/check_series.out.
   - l.5444-5446 "between 38 and 68 digits at seven values of tau": review_K2_d1template_numerics_r0/logs/rC*.log and
     K2_d1template_fix1/composite_tau037.out.
   - l.5446-5447 "56 digits at fourteen points": K2_d1template_fix1/check_lemma1_star.out.
   - l.5448-5449 "between 18 and 25 digits": review_K2_selberg_numerics_r0/partA2_direct2d_0.3.out.
   - l.5449-5450 "54 digits at tau = 0.1 and 0.23": review_K2_selberg_numerics_r0/spectral_hp55*.out.
   - l.5451-5454 "to 37 digits": drafter/check_series.out.
   `make -f public.mk replay-wl` re-runs the Mathematica scripts where Mathematica is available.

Tolerances:
- Exact checks: identical output (sympy 1.11.1). With other sympy versions compare the "= 0" lines.
- Quoted residuals and digit counts: compared at the printed precision. "n digits" means -log10 of the relative (or
  absolute) difference, rounded to the nearest integer. A range "between a and b" passes when every value lies in it
  after rounding.
Checked: Python 3.10.11, mpmath 1.2.1, sympy 1.11.1 (macOS).
"""
import argparse, json, math, re, sys
from pathlib import Path

PKG = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PKG / 'public'))
import mpmath as mp  # noqa: E402
from cf2common import row, quoted, quoted_sci, sha, load, run_pinned, report, versions, mma_abs, same_text  # noqa: E402

RES = PKG / '../../results/closed_forms_2/closed_forms_2.json'


def part_a():
    rc, out, wd, secs, n = run_pinned(PKG, 'L2_singlesums/verify_symbolic.py', work='verify_symbolic')
    npass, nfail = out.count('PASS '), out.count('FAIL ')
    ident = (wd / 'verify_symbolic_report.json').read_bytes() == (PKG / 'L2_singlesums/verify_symbolic_report.json').read_bytes()
    row('L2_singlesums/verify_symbolic.py: exact checks (note l.4899)', f'{npass} PASS, {nfail} FAIL', '31 PASS, 0 FAIL',
        rc == 0 and npass == 31 and nfail == 0, f'{secs:.1f} s; {n} path(s) mapped')
    row('verify_symbolic_report.json regenerated byte-identical', ident, True, ident)

    rc, out, wd, secs, _ = run_pinned(PKG, 'K2_selberg/region_sum_matrix.py', work='region_sum_matrix')
    drop = r'^(region sum - 4 sin|two-term KLT form|tau=)'   # printed on import of region_sum.py (random spot checks)
    imp_ok = all(l.rstrip().endswith('= 0') for l in out.splitlines() if re.match(r'^(region sum - 4 sin|two-term KLT form)', l))
    ok = rc == 0 and same_text(out, (PKG / 'K2_selberg/region_sum_matrix.out').read_text(), drop) and imp_ok
    row('K2_selberg/region_sum_matrix.py (note l.5295): reduced form 4 s^2 (I3^2 + I4^2)', 'same as .out' if ok else 'differs',
        'same as .out', ok, f'{secs:.1f} s; region_sum.py exact checks = 0: {imp_ok}')

    rc, out, wd, secs, _ = run_pinned(PKG, 'K2_selberg/laurent_K2_sympy.py', work='laurent_K2_sympy')
    ok = rc == 0 and same_text(out, (PKG / 'K2_selberg/laurent_K2_sympy.out').read_text()) and \
        'K2 - (32 Cat^2 - 28 zeta3 log2) = 0' in out
    row('K2_selberg/laurent_K2_sympy.py (note l.5390): K2 - (32G^2 - 28 zeta3 log2) = 0', 'same as .out' if ok else 'differs',
        'same as .out', ok, f'{secs:.1f} s')

    rc, out, wd, secs, _ = run_pinned(PKG, 'drafter/check_algebra.py', work='check_algebra')
    ok = rc == 0 and out.strip().endswith('ALL ZERO') and same_text(out, (PKG / 'drafter/check_algebra.out').read_text())
    row('drafter/check_algebra.py: C5(2) algebra, L2 collapse, K2 cells and Laurent (all residuals 0)',
        'ALL ZERO, same as .out' if ok else 'differs', 'ALL ZERO, same as .out', ok, f'{secs:.1f} s')


def digits(x):
    return -math.log10(x)


def part_b():
    rc, out, wd, secs, n = run_pinned(PKG, 'L2_singlesums/check_vs_C62d_dps70.py', work='check_vs_C62d_dps70')
    new = wd / 'check_vs_C62d_dps70.json'; ref = PKG / 'L2_singlesums/check_vs_C62d_dps70.json'
    ident = rc == 0 and new.read_bytes() == ref.read_bytes()
    row('L2_singlesums/check_vs_C62d_dps70.py: JSON byte-identical to the shipped one', ident, True, ident, f'{secs:.1f} s; {n} path(s) mapped')
    d = load(new if new.exists() else ref)
    single = [k for k in d if k.startswith(('a-', 'b-', 'Sy-', 'Sxy-'))]
    worst = max(abs(float(d[k])) for k in single)
    quoted_sci('note l.5144: closed forms of the single sums vs 70-digit values', worst, '3e-70', ', '.join(single))

    worst = 0.0
    for x, want in (('2_5', '1.5e-71'), ('1_2', '1.6e-70'), ('3_5', '5.6e-71')):
        rc, out, wd, secs, _ = run_pinned(PKG, 'public/spec_analyze_scaled.py', [f'spec_{x}.json'], work=f'spec_{x}',
                                          extra_files=[f'review_L2_structural_numerics_r0/spec_{x}.json'])
        m = re.search(r'N=2000 M=10 .* rel diff vs Phi\*Sigma: (\S+)', out)
        v = float(m.group(1)) if (rc == 0 and m) else float('nan')
        worst = max(worst, v) if v == v else float('nan')
        quoted_sci(f'W4(2;2x) spectral vs factorized, x={x.replace("_", "/")} (merge review value)', v, want, f'{secs:.1f} s')
    quoted_sci('note l.5182: W4(2;2x) at x=2/5,1/2,3/5 (largest, rounded)', worst, '2e-70')

    mp.mp.dps = 30
    F = lambda s: mp.hyp3f2(0.5, 0.5, s, 1, 1, 1)
    t = mp.mpf(3) / 10
    J = mp.pi ** 2 * (F(t) ** 2 + F(1 - t) ** 2)
    quoted('note l.5453: pi^2[F(3/10)^2 + F(7/10)^2] (mpmath 3F2, 30 digits)', J, '47.790785413226103671')
    return J


def part_c(J):
    # l.5145-5146: (gc:L2taylor) jets and the chain (1/2)W'(1/2) = L2, s3.log of the L2_singlesums numerics review
    s3 = (PKG / 'review_L2_singlesums_numerics_r0/s3.log').read_text()
    vals = []
    for l in s3.splitlines():
        if l.startswith(('Lemma 4:', 'Prop 4.1 chain')):
            vals.append(mma_abs(l.split('ScientificForm[')[1].rstrip(']')))
    row('note l.5146: jets and chain (1/2)W\'(1/2) = L2 hold to 10^-82 (s3.log, 3 lines)',
        f'max {max(vals):.2e}' if vals else 'none', '10^-82 order', len(vals) == 3 and 1e-83 <= max(vals) < 1e-81)

    cs = (PKG / 'drafter/check_series.out').read_text()
    g = re.search(r'generating functions \(G1,G2,G3\) residuals at k=0.37: \{(.*)\}', cs).group(1).split(', ')
    mom = [mma_abs(re.search(r': (\S+)$', l).group(1)) for l in cs.splitlines()
           if l.startswith(('U0 - 2N', 'int g^2 log k + pi N', 'int f g log k', 'int g^2 log k\''))]
    dg = min(digits(mma_abs(x)) for x in g); dm = min(digits(x) for x in mom)
    # "about 35": the three generating-function residuals lie at 34.3-35.9 digits, the four moments at 38.6-39.3
    row('note l.5148: generating functions and moments hold to about 35 digits (check_series.out)',
        f'{dg:.1f} / {dm:.1f} digits', 'about 35 (>= 34)', dg >= 34 and dm >= 34 and len(g) == 3 and len(mom) == 4,
        'minimum over G1-G3 / over the four moments')

    per_tau = {}
    logs = sorted((PKG / 'review_K2_d1template_numerics_r0/logs').glob('rC*.log')) + [PKG / 'K2_d1template_fix1/composite_tau037.out']
    for f in logs:
        txt = f.read_text(); tau = prec = dig = None
        for l in txt.splitlines():
            m = re.match(r'tau = (\S+)\s+position space J = [0-9.]+`(\d+)', l)
            if m: tau, prec = m.group(1), int(m.group(2))
            if 'difference' in l and 'ScientificForm[0]' in l and prec: dig = max(dig or 0, prec)
            m = re.search(r'InputForm\[Jps - Jcf\] = InputForm\[0``([\d.]+)\]', l)
            if m: dig = max(dig or 0, float(m.group(1)))
        if tau and dig: per_tau[tau] = max(per_tau.get(tau, 0), dig)
    dd = sorted(round(x) for x in per_tau.values())
    row('note l.5446: K2 master vs 2D y-quadrature, between 38 and 68 digits at seven tau',
        f'{len(per_tau)} tau, {dd[0]}..{dd[-1]} digits', '7 tau, 38..68', len(per_tau) == 7 and dd[0] == 38 and dd[-1] == 68,
        ', '.join(f'{k}:{round(v)}' for k, v in sorted(per_tau.items())))

    st = [float(x) for x in re.findall(r'log10\|diff\| < (-[\d.]+)', (PKG / 'K2_d1template_fix1/check_lemma1_star.out').read_text())]
    row('note l.5447: star formula vs one-parameter representation, 56 digits at fourteen points',
        f'{len(st)} points, min {-max(st):.1f}', '14 points, 56', len(st) == 14 and round(-max(st)) == 56)

    rr = [float(x) for x in re.findall(r'rel\.res = (\S+)', (PKG / 'review_K2_selberg_numerics_r0/partA2_direct2d_0.3.out').read_text())]
    lo, hi = digits(max(rr)), digits(min(rr))
    row('note l.5448-5449: twelve cell integrals vs 2I_j, between 18 and 25 digits',
        f'{len(rr)} cells, {lo:.1f}..{hi:.1f}', '12 cells within 18..25', len(rr) == 12 and round(lo) >= 18 and round(hi) <= 25)

    sp = []
    for f in ('spectral_hp55.out', 'spectral_hp55_023.out'):
        m = re.search(r'tau=(\S+): .*rel diff = (\S+)', (PKG / 'review_K2_selberg_numerics_r0' / f).read_text())
        sp.append((m.group(1), digits(float(m.group(2)))))
    row('note l.5450: gs:Ksubtraction (independent spectral code) vs gc:K2master, 54 digits at tau=0.1, 0.23',
        ', '.join(f'{t}:{d:.1f}' for t, d in sp), '0.1, 0.23: 54', [t for t, _ in sp] == ['0.1', '0.23'] and min(round(d) for _, d in sp) == 54)

    m = re.search(r'twelve-term form / pi\^2 - closed form: 0``([\d.]+) \+ 0``([\d.]+)\*I', cs)
    d12 = min(float(m.group(1)), float(m.group(2)))
    row('note l.5454: twelve-term form (direct quadrature of moments) vs closed form at tau=3/10, 37 digits',
        f'{d12:.1f}', '37', int(d12) == 37)
    m = re.search(r'J_\{2tau\} closed at tau=3/10: ([\d.]+)`', cs)
    with mp.workdps(30):
        dj = abs(mp.mpf(m.group(1)) - J)
    row('check_series.out J(3/10) (Mathematica) = mpmath value', mp.nstr(dj, 2), '<= 1e-27', dj <= mp.mpf('1e-27'))

    # cross-check of the stored end-to-end C5(2) of check_series.out with the sibling package's closed form
    m = re.search(r'C5\(2\) simplified formula: (-[\d.]+)`', cs)
    try:
        sys.path.insert(0, str(PKG / '../LRI_C5_d2_simplify/public'))
        from closed_forms_d2 import evaluate
        v = evaluate(40)['C5_2']
        with mp.workdps(40):
            d = abs(mp.mpf(m.group(1)) - v)
        row('[cross-check] check_series.out C5(2) (Mathematica, 30 digits) = closed form', mp.nstr(d, 2), '<= 1e-29', d <= mp.mpf('1e-29'))
    except ImportError:
        row('[cross-check] ../LRI_C5_d2_simplify/public/closed_forms_d2.py available', 'missing', 'present', False)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--test', action='store_true', help='part A only (the exact checks)')
    ap.add_argument('--out', type=Path, default=PKG / 'public/out')
    a = ap.parse_args()
    if not a.test:
        res = load(RES)
        for f in ('L2_singlesums/check_vs_C62d_dps70.json', 'L2_singlesums/verify_symbolic_report.json'):
            h = sha(PKG / f); want = res['record_sha256'][f'LRI_C5_d2_proof/{f}']
            row(f'sha256 of {f} as pinned', h[:16], want[:16], h == want)
    part_a()
    if not a.test:
        part_c(part_b())
    return report(a.out, 'test' if a.test else 'replay', versions())


if __name__ == '__main__':
    sys.exit(main())
