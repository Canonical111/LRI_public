#!/usr/bin/env python3
"""A-RPL-4 (PLAN.md; the accuracy contract; J-VAL-3 in Stage 3b): every tier forced at every point, on the tiers' NATIVE
outputs, against an independent 450-digit value (tests/forced_tiers.cpp `points`).

  python3 -B tests/forced_tiers.py [--loops 7,8] [--l7-graphs 200 --l7-points 256] [--l8-graphs 400 --l8-points 64]
                                   [--min-quad 10000 --min-mp 1000] [--max-points 16384] [--max-seconds 1200]
                                   [--threads N] [--output FILE]
  python3 -B tests/forced_tiers.py --smoke      (8 L7 graphs per sector x 64 points; a tool check, not the gate)
  python3 -B tests/forced_tiers.py --selftest [--exe FILE]   (Mac: the pure-Python checks; with a built forced_tiers
                                                             executable also the tool checks below)

Sample per sector and loop: the heaviest 16 kernels (by M T), power-L7 graphs 228, 1357, 318 and 3754, and random
kernels (seed 4401) up to --l7-graphs / --l8-graphs, replicate 0. The points are the worker's own (layout 0, rate .8,
a 52-bit net, native seed 4401), regenerated by sample(), so the tool's tier decision is checked against evaluate()'s
(d). Gates: (a) ld s <= 1e-14 and binary128 s <= 1e-28 at the points the tier accepts; (b) MP
|m - f450| / (1 + err450) <= 1e-280 at every MP point; (c) the binary128 and MP outputs convert to long double with
relative error <= 2^-64; (d) no decision mismatch. The maxima per tier and loop are the measured column of the
contract table (docs/NUMERICS.md). A breach is a precision-contract finding (status "contract_finding"): reported to
the user, recorded by G3b, never tuned away; Stage 5 waits for the user's answer. Each breach is listed with its point
(graph, replicate, index), tier, value, evaluate()'s level and the 450-digit value (forced_tiers.cpp), so a finding is
recorded precisely.

Verdicts (S1-03): forced_tiers.cpp counts, per point and from its full-precision (450-digit) comparisons, every
condition: ld_scaled, quad_scaled, mp_scaled, quad_conversion and mp_conversion ("breach_counts"; their sum is
"breach_count"). The status comes from those counts and the decision mismatches only; the printed maxima (six digits,
and "full_precision" with 17 significant digits) are display values. Each run's summary must report exactly the task
rows and points it was given (S1-06). Before sampling, the tool checks run on the built executable (L7, the smoke's
net): a worker-style task file is read; a truncated row, a trailing field, a malformed field, a header whose L or row
count differs, and a range, point index or scan beyond the net period are each refused with exit 2 (S1-04, S1-06).

Counts (Stage 3b). The plan asks for at least --min-quad binary128-accepted and --min-mp MP points per sector and loop,
"points per graph double until met". A point counts for a tier when evaluate() hands it to that tier (binary128: the
long-double test failed and the binary128 test passed; MP: both failed). Each round doubles the points of the graphs
that produced points of a tier still short of its count (all graphs when none did) and evaluates only the new index
range [n, 2n) of each, so no point is evaluated twice; a graph stops at --max-points. A (sector, loop) also stops when
the next round's projected wall time (from the last round's seconds per point) would exceed --max-seconds in total.
Counts still short then are recorded ("counts_met": false, with the reason): a coverage shortfall of the sample, not a
precision finding, and reported with the result.
"""
from __future__ import annotations

import argparse
import json
import random
import subprocess
import sys
import tempfile
import time
from decimal import Decimal as D
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import native_common as nc  # noqa: E402
from common import compiler_identity, cxx_command  # noqa: E402

SEED = 4401
POWER_L7 = (228, 1357, 318, 3754)
BOUNDS = {'ld': D('1e-14'), 'quad': D('1e-28'), 'mp': D('1e-280')}
CONV = D(2) ** -64
TIERS = ('ld', 'quad', 'mp')
MAX_BREACHES = 400


def pick(inv, s, L, n, rng):
    rows = inv[s][str(L)]
    heavy = [r['id'] for r in sorted(rows, key=lambda r: -r['cost'])[:16]]
    extra = [g for g in POWER_L7 if s == 'power' and L == 7 and any(r['id'] == g for r in rows)]
    rest = [r['id'] for r in rows if r['id'] not in heavy and r['id'] not in extra]
    return sorted(set(heavy + extra + rng.sample(rest, max(0, min(len(rest), n - len(heavy) - len(extra))))))


CONDITIONS = ('ld_scaled', 'quad_scaled', 'mp_scaled', 'quad_conversion', 'mp_conversion')
MAXIMA = ('max_scaled_all', 'max_scaled_accepted', 'max_relative_all', 'max_relative_accepted', 'max_conversion_relative')


def netfile(td, L):
    """The 52-bit net of loop L (the registered seed SEED + L, tests/fixtures/stage3a_test_seeds.json)."""
    return nc.net(td, nc.dim_of(L, 0), 52, SEED + L)


def points_cmd(exe, root, s, L, netf, tasks, threads):
    return [str(exe), 'points', str(root / s), str(L), str(netf), str(SEED), '0', '.8', '-', str(tasks), str(threads)]


def run_points(exe, root, s, L, ranges, td, threads):
    """ranges: [(graph, begin, end)] of replicate 0 -> the C++ summary of those points. The summary must report exactly
    the rows and points requested (S1-06): a row the tool skipped or a point it did not evaluate is an error."""
    netf = netfile(td, L)
    t = td / f'ft_{s}_{L}.tasks'
    t.write_text(''.join(f'{i} 0 {g} {b} {e} {e}\n' for i, (g, b, e) in enumerate(ranges)))
    cp = subprocess.run(points_cmd(exe, root, s, L, netf, t, threads), capture_output=True, text=True)
    if cp.returncode:
        raise RuntimeError(f'forced_tiers points failed: {cp.stderr[-1500:]}')
    r = json.loads(cp.stdout)
    want = (len(ranges), sum(e - b for _, b, e in ranges))
    if (r.get('rows'), r.get('points')) != want:
        raise RuntimeError(f'forced_tiers points reported {r.get("rows")} rows and {r.get("points")} points; {want[0]} rows and {want[1]} points were requested')
    del r['rows']
    return r


def full(t: dict, k: str) -> D:
    """A tier maximum at full precision (the 17-digit value when the summary has it, else the display value)."""
    return D(t.get('full_precision', {}).get(k, t[k]))


def contract_breaches(r: dict) -> list:
    """The contract findings of one (sector, loop) summary, from forced_tiers.cpp's per-condition counts (S1-03), never
    from the rounded maxima."""
    bc = r.get('breach_counts')
    if (not isinstance(bc, dict) or set(bc) != set(CONDITIONS) or not all(type(v) is int and v >= 0 for v in bc.values())
            or sum(bc.values()) != r['breach_count']):
        raise RuntimeError(f'forced_tiers summary: breach_counts {bc!r} are not five non-negative counts summing to breach_count {r.get("breach_count")!r}')
    bad = [name for k, name in (('ld_scaled', 'ld scaled'), ('quad_scaled', 'binary128 scaled'), ('mp_scaled', 'MP scaled')) if bc[k]]
    if bc['quad_conversion'] or bc['mp_conversion']:
        bad.append('conversion to long double')
    if r['decision_mismatches']:
        bad.append('tier decisions')
    return bad


def _take(acc: dict, new: dict, key: str):
    acc[key] = new[key]
    if 'full_precision' in new:
        acc.setdefault('full_precision', {})[key] = new['full_precision'][key]


def _later_max(acc: dict, new: dict, key: str, at: str):
    if new.get(at) is not None and (acc.get(at) is None or full(new, key) > full(acc, key)):
        _take(acc, new, key)
        acc[at] = new[at]
    elif acc.get(at) is None and full(new, key) > full(acc, key):
        _take(acc, new, key)


def merge(acc: dict | None, r: dict) -> dict:
    """Merges a round's summary into the running one: counts add, maxima keep their point, histograms add."""
    if acc is None:
        return json.loads(json.dumps(r))
    for k in ('points', 'decision_mismatches', 'breach_count'):
        acc[k] += r[k]
    for k in CONDITIONS:
        acc['breach_counts'][k] += r['breach_counts'][k]
    acc['levels'] = [a + b for a, b in zip(acc['levels'], r['levels'])]
    for t in TIERS:
        a, b = acc[t], r[t]
        a['evaluated'] += b['evaluated']
        a['accepted'] += b['accepted']
        for k in ('max_scaled_all', 'max_relative_all'):
            if full(b, k) > full(a, k):
                _take(a, b, k)
        _later_max(a, b, 'max_scaled_accepted', 'at_max_scaled_accepted')
        _later_max(a, b, 'max_relative_accepted', 'at_max_relative_accepted')
        _later_max(a, b, 'max_conversion_relative', 'at_max_conversion')
        h = a['log10_scaled_accepted_histogram']
        for k, v in b['log10_scaled_accepted_histogram'].items():
            h[k] = h.get(k, 0) + v
    acc['breaches'] = (acc['breaches'] + r['breaches'])[:MAX_BREACHES]
    acc['mismatch_examples'] = (acc['mismatch_examples'] + r['mismatch_examples'])[:50]
    gl = acc['graph_levels']
    for g, lv in r['graph_levels'].items():
        gl[g] = [x + y for x, y in zip(gl.get(g, [0, 0, 0]), lv)]
    return acc


def sample_loop(exe, root, s, L, ids, base, a, td):
    """The rounds of one (sector, loop): returns (merged summary, rounds, points per graph, counts_met, reason)."""
    pts = {g: base for g in ids}
    acc, rounds, t_total = None, [], 0.0
    ranges = [(g, 0, base) for g in ids]
    while True:
        t0 = time.time()
        r = run_points(exe, root, s, L, ranges, td, a.threads)
        dt = time.time() - t0
        t_total += dt
        acc = merge(acc, r)
        rounds.append({'graphs': len(ranges), 'points': r['points'], 'seconds': round(dt, 1), 'quad_accepted': acc['quad']['accepted'],
                       'mp_points': acc['mp']['accepted']})
        print(json.dumps({'sector': s, 'L': L, 'round': len(rounds), **rounds[-1]}), flush=True)
        short = [t for t, need in (('quad', a.min_quad), ('mp', a.min_mp)) if acc[t]['accepted'] < need]
        if not short:
            return acc, rounds, pts, True, None
        lv = {int(g): v for g, v in acc['graph_levels'].items()}
        idx = {'quad': 1, 'mp': 2}
        grow = [g for g in ids if pts[g] < a.max_points and any(lv.get(g, [0, 0, 0])[idx[t]] > 0 for t in short)]
        if not grow:
            grow = [g for g in ids if pts[g] < a.max_points]
        if not grow:
            return acc, rounds, pts, False, f'{", ".join(short)} count short with every graph at --max-points {a.max_points}'
        nxt = sum(pts[g] for g in grow)
        projected = dt / max(1, r['points']) * nxt
        if t_total + projected > a.max_seconds:
            return acc, rounds, pts, False, (f'{", ".join(short)} count short; the next round ({nxt} points, projected {projected:.0f} s) would exceed '
                                              f'--max-seconds {a.max_seconds:g} (spent {t_total:.0f} s)')
        ranges = [(g, pts[g], 2 * pts[g]) for g in grow]
        for g in grow:
            pts[g] *= 2


def tool_checks(exe, td) -> dict:
    """S1-04, S1-06 on the built executable: a worker-style task file (header C8D3TASKS1) is read and reports its rows,
    points and the five breach counts; every malformed task file, and a range, point or scan beyond the net period
    (2^52), exits 2 with the reason and prints nothing. On the smallest L7 free kernel with the smoke's net."""
    g = min(nc.inventory()['free']['7'], key=lambda r: (r['cost'], r['id']))['id']
    td = Path(td) / 'tool_checks'
    td.mkdir(exist_ok=True)
    netf, P, refused = netfile(td, 7), 1 << 52, []
    with nc.extracted([('free', 7, g)]) as root:
        def run(name, cmd, rc, reason=None):
            cp = subprocess.run([str(x) for x in cmd], capture_output=True, text=True)
            if cp.returncode != rc or (reason and (reason not in cp.stderr or cp.stdout)):
                raise RuntimeError(f'forced_tiers tool check {name}: exit {cp.returncode} (want {rc}{", " + repr(reason) if reason else ""}): {cp.stderr[-800:]}')
            if rc:
                refused.append(name)
            return cp

        def tasks(name, text, rc, reason=None):
            f = td / f'{name}.tasks'
            f.write_text(text)
            return run(name, points_cmd(exe, root, 'free', 7, netf, f, 2), rc, reason)
        d = json.loads(tasks('worker_header', f'C8D3TASKS1 8 7 2\n0 0 {g} 0 2 2\n\n1 0 {g} 2 3 4\n', 0).stdout)
        if (d['rows'], d['points']) != (2, 3) or set(d['breach_counts']) != set(CONDITIONS) or sum(d['breach_counts'].values()) != d['breach_count']:
            raise RuntimeError(f'forced_tiers tool check worker_header: rows {d["rows"]}, points {d["points"]}, breach_counts {d.get("breach_counts")}')
        for name, text, reason in (('truncated_row', f'0 0 {g} 0 2 2\n1 0 {g} 2\n', 'six fields'),
                                   ('trailing_field', f'0 0 {g} 0 2 2 9\n', 'six fields'),
                                   ('malformed_field', f'0 0 {g} 0 2 2\n1 0 {g} 2 3x 4\n', 'not an unsigned 64-bit integer'),
                                   ('negative_field', f'0 0 {g} 0 2 2\n1 0 {g} -1 3 4\n', 'not an unsigned 64-bit integer'),
                                   ('header_row_count', f'C8D3TASKS1 8 7 3\n0 0 {g} 0 2 2\n1 0 {g} 2 3 4\n', 'declares 3 rows'),
                                   ('header_L', f'C8D3TASKS1 8 6 1\n0 0 {g} 0 2 2\n', 'is not L 7'),
                                   ('header_not_first', f'0 0 {g} 0 2 2\nC7D3TASKS1 7 1\n', 'six fields'),
                                   ('duplicate_uid', f'0 0 {g} 0 2 2\n0 0 {g} 2 3 4\n', 'duplicate task uid'),
                                   ('range_beyond_period', f'0 0 {g} {P - 1} {P + 1} {P + 1}\n', 'beyond the net period')):
            tasks(name, text, 2, reason)
        tail = ['--', root / 'free', 7, netf, SEED, 0, '.8', '-']
        run('point_beyond_period', [exe, '--point', g, 0, 1, P, *tail], 2, 'beyond the net period')
        run('scan_beyond_period', [exe, '--scan', g, 0, P - 1, P + 1, *tail], 2, 'beyond the net period')
    return {'graph': g, 'accepted': 'worker_header', 'refused': refused}


def selftest(exe=None) -> dict:
    """Mac: the pure-Python checks (S1-03 verdicts from the counts, merge, S1-06 row and point counts); with --exe also
    tool_checks on that executable."""
    zero = dict.fromkeys(CONDITIONS, 0)

    def summary(ld_shown, counts, mismatches=0, points=1):
        r = {'L': 7, 'points': points, 'levels': [points, 0, 0], 'decision_mismatches': mismatches, 'breach_count': sum(counts.values()),
             'breach_counts': dict(counts), 'breaches': [], 'mismatch_examples': [], 'graph_levels': {'5': [points, 0, 0]}}
        for tier in TIERS:
            r[tier] = {'evaluated': points, 'accepted': points if tier == 'ld' else 0, 'log10_scaled_accepted_histogram': {},
                       **{k: '0.000000e+00' for k in MAXIMA}, 'full_precision': {k: '0.0000000000000000e+00' for k in MAXIMA},
                       **{k: None for k in ('at_max_scaled_accepted', 'at_max_relative_accepted', 'at_max_conversion')}}
        r['ld']['max_scaled_accepted'] = ld_shown
        return r
    # an accepted scaled error of 1.0000004e-14 is a breach that six digits print as 1.000000e-14; one just below the bound
    # can print above it: the counts decide
    hi = summary('1.000000e-14', {**zero, 'ld_scaled': 1})
    hi['ld']['full_precision']['max_scaled_accepted'] = '1.0000004000000000e-14'
    assert contract_breaches(hi) == ['ld scaled'], contract_breaches(hi)
    lo = summary('1.000001e-14', zero)
    lo['ld']['full_precision']['max_scaled_accepted'] = '9.9999999999999999e-15'
    assert contract_breaches(lo) == [], contract_breaches(lo)
    assert contract_breaches(summary('0', {**zero, 'mp_conversion': 2})) == ['conversion to long double']
    assert contract_breaches(summary('0', {**zero, 'quad_scaled': 1, 'mp_scaled': 1}, mismatches=1)) == ['binary128 scaled', 'MP scaled', 'tier decisions']
    for bad in ({**zero, 'ld_scaled': 1}, None, {k: 0 for k in CONDITIONS[:4]}):
        r = summary('0', zero)
        r['breach_counts'] = bad
        try:
            contract_breaches(r)
        except RuntimeError:
            continue
        raise AssertionError(f'inconsistent breach_counts {bad} accepted')
    # merge: counts add; a maximum is taken at full precision (the display values tie)
    m = merge(None, lo)
    m = merge(m, hi)
    assert m['breach_counts']['ld_scaled'] == 1 and m['breach_count'] == 1
    assert m['ld']['max_scaled_accepted'] == '1.000000e-14' and m['ld']['full_precision']['max_scaled_accepted'] == '1.0000004000000000e-14', m['ld']
    # run_points: the summary must report exactly the rows and points requested (a fake executable)
    with tempfile.TemporaryDirectory(prefix='c8d3_forced_selftest_') as td:
        td = Path(td)
        for rows, pts, ok_ in ((2, 5, True), (1, 2, False), (2, 4, False)):
            fake = td / 'fake_forced_tiers'
            fake.write_text(f'#!{sys.executable}\nimport json\nprint(json.dumps({{**json.loads({json.dumps(json.dumps(summary("0", zero, points=pts)))}), "rows": {rows}}}))\n')
            fake.chmod(0o755)
            try:
                r = run_points(fake, td, 'free', 7, [(5, 0, 2), (5, 2, 5)], td, 1)
            except RuntimeError as e:
                assert not ok_ and 'requested' in str(e), e
                continue
            assert ok_ and 'rows' not in r and r['points'] == 5, (rows, pts, r)
        res = {'status': 'passed', 'checks': ['verdict_from_counts', 'inconsistent_counts_refused', 'merge_full_precision', 'rows_and_points_asserted']}
        if exe:
            res['tool_checks'] = tool_checks(Path(exe).resolve(), td)
    return res


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--loops', default='7,8')
    ap.add_argument('--l7-graphs', type=int, default=200)
    ap.add_argument('--l7-points', type=int, default=256)
    ap.add_argument('--l8-graphs', type=int, default=400)
    ap.add_argument('--l8-points', type=int, default=64)
    ap.add_argument('--min-quad', type=int, default=10000)
    ap.add_argument('--min-mp', type=int, default=1000)
    ap.add_argument('--max-points', type=int, default=1 << 14, help='points per graph at most (the doubling stops there)')
    ap.add_argument('--max-seconds', type=float, default=1200., help='wall seconds per (sector, loop) for the doubling rounds')
    ap.add_argument('--threads', type=int, default=nc.threads_default())
    ap.add_argument('--smoke', action='store_true')
    ap.add_argument('--selftest', action='store_true', help='the pure-Python checks (and, with --exe, the tool checks); no sampling')
    ap.add_argument('--exe', type=Path, help='with --selftest: a built forced_tiers executable')
    ap.add_argument('--output', type=Path)
    a = ap.parse_args(argv)
    if a.selftest:
        res = selftest(a.exe)
        nc.dump(a.output, res)
        print(json.dumps(res, indent=2))
        return
    if a.smoke:
        a.loops, a.l7_graphs, a.l7_points, a.min_quad, a.min_mp = '7', 8, 64, 0, 0
    inv = nc.inventory()
    loops = [L for L in map(int, a.loops.split(',')) if str(L) in inv['free']]
    rng = random.Random(SEED)
    out, findings, shortfalls = [], [], []
    t0 = time.time()
    with tempfile.TemporaryDirectory(prefix='c8d3_forced_') as td:
        td = Path(td)
        exe = td / 'forced_tiers_gmp'
        cmd = cxx_command([nc.ROOT / 'tests/forced_tiers.cpp'], exe, defines=('C7_USE_GMP',), libs=('-lquadmath', '-lgmp'))
        subprocess.run(cmd, check=True)
        build = {**compiler_identity(cmd), 'executable_sha256': nc.digest(exe)}
        checks = tool_checks(exe, td)
        print(json.dumps({'tool_checks': checks}), flush=True)
        for L in loops:
            for s in nc.SECTORS:
                n, pts = (a.l7_graphs, a.l7_points) if L == 7 else (a.l8_graphs, a.l8_points)
                ids = pick(inv, s, L, n, rng)
                with nc.extracted([(s, L, g) for g in ids]) as root:
                    r, rounds, per, met, why = sample_loop(exe, root, s, L, ids, pts, a, td)
                hist = {}
                for p in per.values():
                    hist[p] = hist.get(p, 0) + 1
                r.update(sector=s, base_points_per_graph=pts, points_per_graph_histogram={str(k): v for k, v in sorted(hist.items())},
                         rounds=rounds, counts_met=met, counts_shortfall=why, graph_ids=ids,
                         counts={'quad_accepted': r['quad']['accepted'], 'mp_points': r['mp']['accepted'], 'min_quad': a.min_quad, 'min_mp': a.min_mp})
                bad = contract_breaches(r)
                r['contract_breaches'] = bad
                findings += [f'{s} L{L}: {b}' for b in bad]
                if not met:
                    shortfalls.append(f'{s} L{L}: {why}')
                out.append(r)
                print(json.dumps({k: v for k, v in r.items() if k not in ('graph_levels', 'graph_ids')}), flush=True)
    res = {'status': 'contract_finding' if findings else 'passed', 'smoke': a.smoke, 'findings': findings,
           'counts_status': 'met' if not shortfalls else 'shortfall', 'count_shortfalls': shortfalls, 'results': out, 'build': build, 'tool_checks': checks,
           'bounds': {k: str(v) for k, v in BOUNDS.items()}, 'conversion_bound': '2^-64',
           'sampling': {'seed': SEED, 'rate': '.8', 'layout': 0, 'bits': 52, 'replicate': 0, 'max_points': a.max_points,
                        'max_seconds': a.max_seconds, 'doubling': 'per graph, the graphs producing points of a short tier (all when none); new index ranges only'},
           'host': nc.host_info(), 'wall_seconds': round(time.time() - t0, 1)}
    nc.dump(a.output, res)
    print(json.dumps({k: v for k, v in res.items() if k != 'results'}, indent=2))


if __name__ == '__main__':
    main()
