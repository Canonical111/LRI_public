#!/usr/bin/env python3
"""Write numbers_d1.tex from quoted_numbers_d1.json (a copy of HT/results/HT_1d/quoted_numbers.json).

Every d = 1 number of the note is typeset through \\HTq{<id>}, so the note quotes exactly the values that the replay
(HT/code/lri_dressed_phi4_hpc_analysis/public/replay_ht1d.py) checks. `--check` exits 1 if numbers_d1.tex is stale.
"""
import json, re, sys
from pathlib import Path
HERE = Path(__file__).resolve().parents[1]

def tex(v):
    if isinstance(v, bool): return 'yes' if v else 'no'
    if isinstance(v, (int, float)) and not isinstance(v, bool): v = str(v)
    if isinstance(v, list): return '\\text{--}'.join(tex(x) for x in v)
    m = re.fullmatch(r'(-?[0-9.]+)e(-?[0-9]+)', v)
    if m:
        a, b = m.groups(); b = str(int(b))
        return ('10^{%s}' % b) if a in ('1', '1.0') else ('%s\\times10^{%s}' % (a, b))
    return v.replace('–', '\\text{--}')

def build():
    Q = json.loads((HERE / 'data/quoted_numbers_d1.json').read_text())['numbers']
    out = ['% Generated by tools/gen_numbers_d1.py from data/quoted_numbers_d1.json (= HT/results/HT_1d/quoted_numbers.json).',
           '% Do not edit by hand; \\HTq{<id>} typesets the quoted value of row <id> (math mode).',
           '\\newcommand{\\HTq}[1]{\\csname HTq@#1\\endcsname}']
    for q in Q:
        v = q['quoted']
        val = '\\text{%s}' % re.sub(r'\bDs\b', r'$\\Delta_\\sigma$', q['display']) if 'display' in q else ', '.join(tex(x) for x in v) if q['compare'].startswith('list') else tex(v)
        out.append('\\expandafter\\def\\csname HTq@%s\\endcsname{%s}' % (q['id'], val))
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    new = build(); p = HERE / 'numbers_d1.tex'
    if '--check' in sys.argv:
        ok = p.exists() and p.read_text() == new
        print('numbers_d1.tex', 'up to date' if ok else 'STALE'); sys.exit(0 if ok else 1)
    p.write_text(new); print('wrote', p)
