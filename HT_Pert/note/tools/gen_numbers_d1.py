#!/usr/bin/env python3
"""Write numbers_d1.tex (the d = 1 macros of the note) from data/quoted_numbers_d1.json, a copy of
HT_Pert/results/HT_1d/quoted_numbers.json (every quoted d = 1 number with its replay row). Paper macros keep the
paper's names and values; note-only macros start with \\NOne."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def main():
    q = json.load(open(os.path.join(ROOT, "data", "quoted_numbers_d1.json")))
    seen, lines = {}, ["% numbers_d1.tex: generated by tools/gen_numbers_d1.py from data/quoted_numbers_d1.json; do not edit.",
                       "% Every macro has a replay row (column 'id'); see the reproduction section."]
    for e in q["numbers"]:
        m = e.get("macro") or ""
        if not m.startswith("\\") or m in seen:
            if m in seen and seen[m] != e["quoted"]:
                raise SystemExit(f"{m}: two different values {seen[m]!r} and {e['quoted']!r}")
            continue
        seen[m] = e["quoted"]
        lines.append(f"\\providecommand{{{m}}}{{{e['quoted']}}}   % {e['id']}: {e['what']}")
    open(os.path.join(ROOT, "numbers_d1.tex"), "w").write("\n".join(lines) + "\n")
    print(f"numbers_d1.tex: {len(seen)} macros")


if __name__ == "__main__":
    main()
