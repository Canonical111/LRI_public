#!/usr/bin/env python3
"""Write sections/repro_d1.tex (the d = 1 rows of the reproduction longtable) from data/quoted_numbers_d1.json, a copy
of HT_Pert/results/HT_1d/quoted_numbers.json. Columns: result & value & pkg & records & command & tolerance. The command
is 'replay <id>' of the package (make -f public.mk replay in code/<package>). The result labels and the plain-text
values are taken from tools/repro_labels_d1.py; integrity rows are merged into one row per package. Every row of the
expectation file must be either labelled or merged, else the script stops."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from repro_labels_d1 import INTEGRITY, LABELS, VALUES  # noqa: E402

PKG = {  # package -> (letter, records)
    "lri_hpc_Hamitonian": ("S", "T, A"),
    "lri_eh_hpc": ("G", "A"),
    "lri_c8_hpc": ("E", "C8"),
    "lri_d1_full_coefficient_flow": ("W", "S10"),
    "lri_1d_dconn_refit": ("R", "R, A"),
    "lri_1d_c4_exact": ("X4", "X4"),
    "lri_1d_c5_exact": ("X5", "X5"),
    "lri_d1_fullblock_tail_response": ("F", "F"),
}


def esc(s):
    return s.replace("\\", "\\char92{}").replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def rid(s):
    """A replay id in \\code, breakable after each dot."""
    return "\\code{" + esc(s).replace(".", ".\\allowbreak{}") + "}"


def value(e):
    if e["id"] in VALUES:
        return VALUES[e["id"]]
    v = str(e["quoted"])
    if not e.get("macro"):
        return esc(v)
    if "\\text{ to }" in v:  # a range: two math pieces, so the cell can break
        a, b = v.split("\\text{ to }")
        return f"${a}$ to ${b.strip('{}')}$"
    if ", " in v and "{" not in v:  # a list of numbers
        return ", ".join(f"${x}$" for x in v.split(", "))
    return f"${v}$"


def tol(e):
    c = str(e.get("compare", "")).lower()
    if c.startswith("exact") or c.startswith("equal") or c == "refit 1e-9":
        return "exact"
    if "info" in c or "judgement" in c or c.startswith("none"):
        return "info"
    if c.startswith("le") or "bound" in c:
        return "bound"
    if c.startswith("reading"):
        return "reading"
    return "as stated"


def main():
    q = json.load(open(os.path.join(ROOT, "data", "quoted_numbers_d1.json")))
    head = ("\\multicolumn{6}{@{}p{\\linewidth}@{}}{\\emph{$d=1$} (packages: " +
            ", ".join(f"{v[0]} = \\code{{{k.replace('_', chr(92) + '_')}}}" for k, v in PKG.items()) +
            "; records: T = \\code{data/HT\\_1d/thermal\\_expanse}, A = the package's \\code{analysis/}, "
            "C8 = \\code{data/HT\\_1d/c8}, S10 = \\code{data/HT\\_1d/s10\\_production}, R = the package's summary "
            "outputs, X4, X5 = \\code{data/HT\\_1d/exact\\_c4}, \\code{exact\\_c5}, F = the package's \\code{results/}. "
            "Each package's integrity checks (code fingerprints, checksum lists, self-hashed records, gates) are merged "
            "into one row; \\code{results/HT\\_1d/quoted\\_numbers.json} describes every row.)}\\\\")
    out = ["% repro_d1.tex: generated by tools/gen_repro_d1.py from data/quoted_numbers_d1.json and"
           " tools/repro_labels_d1.py; do not edit.", head]
    groups = {}
    for e in q["numbers"]:
        if e["id"] in INTEGRITY:
            groups.setdefault(e["package"], []).append(e["id"])
    done, missing = set(), []
    for e in q["numbers"]:
        letter, rec = PKG.get(e["package"], ("?", "?"))
        if e["id"] in INTEGRITY:
            if e["package"] in done:
                continue
            done.add(e["package"])
            ids = ",\\allowbreak{} ".join(rid(i) for i in groups[e["package"]])
            out.append(f"integrity of code and records & pass & {letter} & {rec} & replay {ids} & exact\\\\")
            continue
        key = (e["id"], e.get("macro"))
        if key not in LABELS:
            missing.append(key)
            continue
        out.append(f"{LABELS[key]} & {value(e)} & {letter} & {rec} & replay {rid(e['id'])} & {tol(e)}\\\\")
    if missing:
        sys.exit("no label for: " + ", ".join(map(str, missing)))
    unused = set(LABELS) - {(e["id"], e.get("macro")) for e in q["numbers"]}
    if unused:
        sys.exit("labels for rows that do not exist: " + ", ".join(map(str, sorted(unused, key=str))))
    open(os.path.join(ROOT, "sections", "repro_d1.tex"), "w").write("\n".join(out) + "\n")
    print(f"repro_d1.tex: {len(out) - 2} rows")


if __name__ == "__main__":
    main()
