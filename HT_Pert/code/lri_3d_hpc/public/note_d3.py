#!/usr/bin/env python3
"""The d = 3 finite-cutoff table of the HT_Pert note (tab_d3_coeffs.tex) from the shipped records.

C_n(L), n = 2..8, at L = 16, 18, 20 in both schemes of this package (10 significant digits). Standard library only.

Run from code/lri_3d_hpc:  python3 -B public/note_d3.py --out <dir>   (writes <dir>/tab_d3_coeffs.tex)
"""
import argparse, json
from decimal import Decimal, getcontext
from pathlib import Path

getcontext().prec = 40
PKG = Path(__file__).resolve().parent.parent
CONT = {2: '0.18122178540555422213', 3: '-0.353581520433', 4: '1.22806354532762307997', 5: '-5.8503514207513272292',
        6: '33.57542664131543', 7: '-220.35448047392794', 8: '1602.6052229663408'}   # replay_pert3d.py, CONT


def sig(x, n=10):
    """x to n significant digits, TeX minus sign."""
    s = f'{Decimal(x):.{n}g}' if abs(Decimal(x)) < 1e6 else f'{Decimal(x):.{n}e}'
    return s.replace('-', '$-$')


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--data', default=str(PKG / '../../data/HT_3d/pert3d'))
    ap.add_argument('--out', default=str(PKG / '.work/note'))
    a = ap.parse_args()
    res = {(L, s): json.loads((Path(a.data) / f'results/L{L}/c{L}_{s}.json').read_text())['result']['C']
           for L in (16, 18, 20) for s in ('raw', 'consistent')}
    rows = []
    for n in range(2, 9):
        cells = [sig(res[L, s][n]) for s in ('consistent', 'raw') for L in (16, 18, 20)]
        rows.append(f'$C_{n}$ & ' + ' & '.join(cells[:3]) + ' & ' + ' & '.join(cells[3:]) + '\\\\')
    tex = ['% tab_d3_coeffs.tex: generated by code/lri_3d_hpc/public/note_d3.py from data/HT_3d/pert3d/results (do not edit)',
           '\\begin{table}[ht]\\centering\\footnotesize\\setlength{\\tabcolsep}{3pt}',
           '\\begin{tabular}{@{}l lll lll@{}}\\toprule',
           ' & \\multicolumn{3}{c}{consistent (vacuum window $D_L$)} & \\multicolumn{3}{c}{raw}\\\\',
           '\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}',
           ' & $L=16$ & $L=18$ & $L=20$ & $L=16$ & $L=18$ & $L=20$\\\\\\midrule',
           *rows,
           '\\bottomrule\\end{tabular}',
           '\\caption{Finite-cutoff coefficients $C_n(L)$ in $d=3$ from the production package \\code{lri\\_3d\\_hpc} '
           '(10 significant digits; the records hold 20), raw and with the vacuum window $D_L$. $C_2$ and $C_3$ do not '
           'depend on the window. The exact sums reproduce $C_2$ to $C_5$ of this table to $3\\times10^{-13}$; from $C_4$ '
           'on, neither scheme converges (Fig.~\\ref{d3:fig:c4}).}',
           '\\label{d3:tab:coeffs}\\end{table}']
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / 'tab_d3_coeffs.tex').write_text('\n'.join(tex) + '\n')
    print(f'wrote {out / "tab_d3_coeffs.tex"}')


if __name__ == '__main__':
    main()
