#!/usr/bin/env python3
"""Fast test of the integ_d1 package (new tool, 2026-10-18). Run from code/integ_d1/. A few minutes on 8 cores.
 1. snapshot   public/SNAPSHOT.sha256: every exported file of the project at commit 8bd5a22 (files listed in
               public/SCRUBBED.txt, written by the public repository's scrub: presence only);
 2. git table  public/git_blobs.json: every blob id the git stand-in (public/gitstub.py) answers equals the git blob id
               of the shipped file it serves (code/, results/, or public/historic/ for the older engine source);
 3. records    every record of results/frozen_records.json and the six of the note's App. I.8 against their sha256;
 4. engine     the engine and the sector checker built from source with code/build_engine.sh, build_checker.sh (g++,
               -march=x86-64-v3, OpenMP): the double and double-double build ids must equal the production ids of
               results/builds.json, and the delta^2 build of the f_2_0_2 runs, rebuilt from its own source
               (public/historic/b2ab7c6/cluster_engine.cpp), must give its id too;
 5. unit tests code/test_cluster.py (engine regression tests against the two-bubble record and the exact Bethe ansatz),
               code/test_gates.py (negative and positive tests of every gate; its local clones go through the git
               stand-in) and code/test_two_bubble.py (the independent mpmath two-bubble integrator of M2 vs the exact
               Bethe ansatz at K = 0.3, level 2: about 3 min on one core, run alongside the other tests);
 6. reruns     a few sectors of four production chunks (fine, radius, complex K, f_202) rerun with the rebuilt engines
               from their recorded arguments (the n = 4 input regenerated by code/cluster_gen.py and checked against its
               manifest hash) and compared with the shipped outputs coefficient by coefficient at 40 digits:
               |rerun - shipped| <= 4 eps B, with B the engine's first-order magnitude bound of that coefficient (|value|
               for the f_202 runs, which carry no bounds) and eps = 2^-53 (double) or 2^-104 (double-double); the number of
               bitwise-identical values is reported.
Usage: python3 public/selftest_integ.py [--work DIR] [--skip-engine] [--threads N]
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
PKG = HERE.parent
sys.path.insert(0, str(PKG.parent.parent/'verify'))
import sri_lib as SL  # noqa: E402
sys.path.insert(0, str(HERE))
from replay_integ import APP_I8, setup  # noqa: E402

PROD_BUILDS = {'double': ('b0da6f7bc003c829', ['-DUSE_DOUBLE']), 'dd': ('06c88f4c378ed21d', [])}
M4A_BUILD = ('5345fdf1bcec7a5a', ['-DLS=13', '-DVMIN=-8'])
# (label, shipped output, engine build of the rerun, sector range, tolerance factor x eps x B with eps of the build that
# wrote the shipped output); the arguments are read from the shipped header. (The double-double production outputs are
# heavy sectors, minutes each even on 40 cores; the double-double build is tested by test_cluster.py, and the gate
# checks every shipped double-double override against the double output within the double roundoff bound.)
RERUNS = [('F (fine, double)', 'results/m4_runs/prod/F/c1_202.out', 'double', (202, 207), 4),
          ('R (radius, double)', 'results/m4_runs/prod/R/c0_0.out', 'double', (217, 221), 4),
          ('cxA (complex K, double)', 'results/m4_runs/prod/cxA/c0_0.out', 'double', (217, 221), 4),
          ('n3d2_A (f_202, delta^2 build)', 'results/m4_runs/n3d2_A/c0.out', 'm4a', (19, 23), 4)]
SHIPPED_EPS = {'prod': 2.0 ** -53, 'n3d2': 2.0 ** -104}


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def blob_id(data):
    return hashlib.sha1(b'blob %d\0' % len(data) + data).hexdigest()


def scrubbed():
    f = HERE/'SCRUBBED.txt'
    return {l.strip() for l in f.read_text().splitlines() if l.strip() and not l.startswith('#')} if f.exists() else set()


def build(src_dir, out, flags, log):
    r = subprocess.run(['bash', str(src_dir/'build_engine.sh'), str(out)] + flags, capture_output=True, text=True)
    log.write_text(r.stdout + r.stderr)
    return r.stdout.strip().splitlines()[-1] if r.returncode == 0 and r.stdout.strip() else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--work', default=str(PKG/'.work'/'test'))
    ap.add_argument('--skip-engine', action='store_true')
    ap.add_argument('--threads', type=int, default=int(os.environ.get('OMP_NUM_THREADS', '0') or os.cpu_count() or 1))
    a = ap.parse_args()
    work = Path(a.work).resolve()
    T = SL.Table('integ_d1 test')
    t0 = time.time()
    times = {}

    # 1. snapshot ------------------------------------------------------------------------------------------------------
    S = scrubbed()
    bad, n, ns = [], 0, 0
    for line in (HERE/'SNAPSHOT.sha256').read_text().splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        h, rel = line.split(None, 1)
        n += 1
        p = PKG/rel
        if not p.exists():
            bad.append(rel + ' (missing)')
        elif rel in S:
            ns += 1
        elif sha(p) != h:
            bad.append(rel)
    T.check('verbatim snapshot', not bad, '%d files (%d scrubbed: presence only)%s' % (n, ns, '; differ: %s' % bad[:4] if bad else ''),
            'all sha256 equal', 'public/SNAPSHOT.sha256 (git objects of LRI_SRI_integrability at 8bd5a22)')

    # 2. git table ----------------------------------------------------------------------------------------------------
    tab = json.loads((HERE/'git_blobs.json').read_text())
    bad = []
    for key, bid in tab['blobs'].items():
        f = PKG/tab['historic'][key] if key in tab.get('historic', {}) else PKG/key.split(':', 1)[1]
        if not f.is_file() or blob_id(f.read_bytes()) != bid:
            bad.append(key)
    for path in tab['first_added']:
        if not (PKG/path).is_file():
            bad.append(path)
    T.check('git stand-in table', not bad, '%d blob ids, %d first-add commits, %d historic file(s)%s' % (
        len(tab['blobs']), len(tab['first_added']), len(tab.get('historic', {})), '; differ: %s' % bad if bad else ''),
        'every blob id = git hash-object of the shipped file', 'public/git_blobs.json')

    # 3. records ------------------------------------------------------------------------------------------------------
    reg = json.loads((PKG/'results'/'frozen_records.json').read_text())
    bad = [k for k, e in reg.items() if sha(PKG/'results'/k) != e['sha256']] + \
          [k for k, h in APP_I8.items() if sha(PKG/'results'/k) != h]
    T.check('record sha256', not bad, '%d registered + the 6 of App. I.8%s' % (len(reg), '; differ: %s' % bad if bad else ''),
            'all equal', 'results/frozen_records.json; App. I.8 of the note')

    if a.skip_engine:
        T.add('engine, unit tests, reruns', 'SKIP', '--skip-engine', '-', '-')
        sys.exit(T.report(work.parent/'selftest_integ_table.txt'))

    # 4. engine builds ------------------------------------------------------------------------------------------------
    run, env = setup(work)
    env['OMP_NUM_THREADS'] = str(a.threads)
    code, B, L = run/'code', work/'bin', work/'logs'
    tb = time.time()
    from concurrent.futures import ThreadPoolExecutor
    hist = work/'m4a_src'
    hist.mkdir()
    for f in ('dd.h', 'sha256.h', 'build_engine.sh'):
        shutil.copy(code/f, hist/f)
    shutil.copy(PKG/tab['historic']['b2ab7c6:code/cluster_engine.cpp'], hist/'cluster_engine.cpp')
    jobs = {'double': (code, B/'ce_double', PROD_BUILDS['double'][1]), 'dd': (code, B/'ce_dd', PROD_BUILDS['dd'][1]),
            'k2': (code, B/'ce_k2', ['-DLS=13', '-DVMIN=-8']), 'm4a': (hist, B/'ce_m4a', M4A_BUILD[1])}
    with ThreadPoolExecutor(5) as ex:
        fut = {k: ex.submit(build, s, o, f, L/('build_%s.txt' % k)) for k, (s, o, f) in jobs.items()}
        rc = subprocess.run(['bash', str(code/'build_checker.sh'), str(B/'sector_check')], capture_output=True, text=True)
        ids = {k: f.result() for k, f in fut.items()}
    times['builds'] = time.time() - tb
    T.check('engine build ids', ids['double'] == PROD_BUILDS['double'][0] and ids['dd'] == PROD_BUILDS['dd'][0] and ids['m4a'] == M4A_BUILD[0]
            and ids['k2'] is not None and rc.returncode == 0,
            'double %s, dd %s, delta^2 (b2ab7c6) %s; checker %s' % (ids['double'], ids['dd'], ids['m4a'], 'built' if rc.returncode == 0 else 'FAILED'),
            '%s, %s, %s' % (PROD_BUILDS['double'][0], PROD_BUILDS['dd'][0], M4A_BUILD[0]),
            'build_engine.sh: id = sha256(sources + compile command); g++ -O3 -march=x86-64-v3 -ffp-contract=off -fopenmp')

    # 5. unit tests ---------------------------------------------------------------------------------------------------
    def py(name, args, cwd=code, timeout=3600):
        t = time.time()
        r = subprocess.run([sys.executable] + args, cwd=cwd, env=env, capture_output=True, text=True, timeout=timeout)
        times[name] = time.time() - t
        (L/(name + '.txt')).write_text(r.stdout + r.stderr)
        return r.returncode, r.stdout + r.stderr
    t2b = time.time()
    tb2 = subprocess.Popen([sys.executable, 'test_two_bubble.py', '2', '0.3', '25'], cwd=code, env=dict(env, OMP_NUM_THREADS='1'),
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    rc, out = py('test_cluster', ['test_cluster.py', str(B/'ce_dd'), str(B/'sector_check'), '--k2', str(B/'ce_k2')])
    T.check('test_cluster.py', rc == 0 and 'ALL PASS' in out, '%d PASS, %d FAIL' % (out.count('PASS '), out.count('FAIL ')),
            'ALL PASS', 'engine vs two-bubble record (<1e-28), exact Bethe ansatz (<1e-27), delta paths, radii, guards')
    rc, out = py('test_gates', ['test_gates.py'])
    T.check('test_gates.py', rc == 0 and 'ALL PASS' in out, '%d PASS, %d FAIL' % (out.count('PASS '), out.count('FAIL ')),
            'ALL PASS', 'negative/positive tests of the M2, M3, M4A, M4B, cx and C8 gates (fix rounds 1-5)')
    out, _ = tb2.communicate()
    times['test_two_bubble'] = time.time() - t2b
    (L/'test_two_bubble.txt').write_text(out)
    m = re.search(r'rel diff\s+:\s+(\S+)', out)
    rel = float(m.group(1)) if m else float('inf')
    T.check('test_two_bubble.py (K = 0.3, level 2)', tb2.returncode == 0 and rel < 1e-9, 'rel diff %s' % (m.group(1) if m else '-'),
            '< 1e-9', 'the mpmath two-bubble integrator of M2 (two_bubble.py), J2^(0) vs the exact Bethe ansatz')

    # 6. production reruns --------------------------------------------------------------------------------------------
    sys.path.insert(0, str(code))
    from cluster_assemble import read_out
    n4 = work/'n4.txt'
    rc, _ = py('cluster_gen_n4', ['cluster_gen.py', '4', str(n4), '--no-radii'])
    man = json.loads((run/'results'/'m4_inputs'/'n4.manifest.json').read_text())
    T.check('n = 4 engine input regenerated', rc == 0 and sha(n4) == man['input_sha256'], sha(n4)[:16] if n4.exists() else '-',
            man['input_sha256'][:16], 'cluster_gen.py 4 --no-radii; sha256 = results/m4_inputs/n4.manifest.json')
    inputs = {'n4.txt': n4, 'n3.txt': run/'results'/'m3_inputs'/'n3.txt'}
    eps = {'double': 2.0 ** -53, 'dd': 2.0 ** -104, 'm4a': 2.0 ** -104}
    exe = {'double': B/'ce_double', 'dd': B/'ce_dd', 'm4a': B/'ce_m4a'}
    import mpmath as mp
    mp.mp.dps = 40
    for lab, rel, bld, (s0, s1), fac in RERUNS:
        ship = run/rel
        hdr = [l for l in ship.read_text().splitlines()[:5] if l.startswith('# args ')][0].split()[2:]
        args = hdr[hdr.index('-i') + 2:] if hdr[0] == '-o' else hdr
        i = args.index('-sec')
        args[i + 1:i + 3] = [str(s0), str(s1)]
        inp = inputs[hdr[hdr.index('-i') + 1]]
        out = work/('rerun_%s_%d.out' % (bld, s0))
        t = time.time()
        r = subprocess.run([str(exe[bld]), '-o', str(out), '-i', str(inp)] + args, env=env, capture_output=True, text=True)
        times['rerun ' + lab] = time.time() - t
        if r.returncode != 0:
            T.check('rerun ' + lab, False, 'engine exit %d: %s' % (r.returncode, r.stderr[-200:]), '-', '-')
            continue
        _, sa = read_out(str(ship))
        _, sb = read_out(str(out))
        secs = [x for x in range(s0, s1) if x in sa]
        eps0 = SHIPPED_EPS['n3d2' if 'n3d2' in rel else 'prod']
        worst, nval, nsame, missing = mp.mpf(0), 0, 0, []
        for x in secs:
            if x not in sb:
                missing.append(x)
                continue
            A, Bs = sa[x], sb[x]
            vals = [(('S',) + k, v, Bs['S'].get(k), (A.get('B') or {}).get(k)) for k, v in A['S'].items()] + \
                   [(('A',) + k, v, Bs['A'].get(k), (A.get('B') or {}).get(k)) for k, v in A['A'].items()]   # ser / cx mode
            for key, v, w, bnd in vals:
                if w is None:
                    missing.append((x, key))
                    continue
                nval += 1
                d = abs(v - w)                       # double-double values, compared at 40 digits
                nsame += d == 0
                tol = fac * eps0 * (bnd if bnd is not None else abs(v))
                if tol > 0:
                    worst = max(worst, d / tol)
                elif d:
                    worst = mp.inf
        T.check('rerun ' + lab, not missing and bool(secs) and worst <= 1, '%d sectors, %d values, %d bitwise identical; max |diff|/(%d eps B) %s' % (
            len(secs), nval, nsame, fac, mp.nstr(worst, 2)), '<= 1', '%s sectors %d-%d (%s build), arguments of the shipped header' % (rel, s0, s1 - 1, bld))
    T.add('timing', 'INFO', ', '.join('%s %.0fs' % kv for kv in times.items()), '-', 'total %.0f s, %d threads' % (time.time() - t0, a.threads))
    st = T.report(work.parent/'selftest_integ_table.txt')
    if st == 0:
        shutil.rmtree(work, ignore_errors=True)
    sys.exit(st)


if __name__ == '__main__':
    main()
