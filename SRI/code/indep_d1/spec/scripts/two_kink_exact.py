#!/usr/bin/env python3
"""Exact eps-expansions of the elementary two-kink raw atoms Z2_<der> and Q2_<der>.

ARCHIVE-FREE.  Derived here from the definitions only:
  Z2(v,delta;eps) = int_eps^1 (1-r) W2 dr,      Q2 = int_eps^1 (1-r) r W2 dr,
  W2 = exp[2 v q1 q2 f_delta(r)] = exp[-2 v f_delta(r)],  f_delta(r) = (r^delta-1)/delta,
(the translation integral over X1 gives the factor 1-r; the dipole D2 = r).
The derivative insertions d_v^a d_delta^b W2 / W2 at (1,0) are derived from the exponent
(independently of the INS table of build_spec.py, which is checked against them for n=2).
Every coefficient is an exact rational: int_eps^1 r^n log^j r dr is elementary.

Output: ../out/two_kink_exact.json   {atom: {p: {k: "rational"}}}  (full expansion; all
other [eps^p l^k] are exactly zero).  These may be used directly as raw inputs and are
validation targets for any integration engine.
"""
import json
from fractions import Fraction
from math import factorial
from pathlib import Path
import sympy as s

OUT = Path(__file__).resolve().parent.parent / 'out'
DERS = {'base': (0, 0), 'v': (1, 0), 'vv': (2, 0), 'vvv': (3, 0), 'd': (0, 1), 'vd': (1, 1),
        'vvd': (2, 1), 'dd': (0, 2), 'vdd': (1, 2)}

w, dl, L = s.symbols('w dl L')     # v = 1 + w ; L = log r


def insertion(a, b):
    """d_v^a d_delta^b W2 / W2 at (v,delta) = (1,0), as a polynomial in L = log r."""
    order = a + b + 1
    f = sum(dl**k * L**(k + 1) / s.factorial(k + 1) for k in range(order + 1))
    X = -2 * (1 + w) * f                      # 2 v q1 q2 f_delta, q1 q2 = -1
    Y = s.expand(X - X.subs({w: 0, dl: 0}))
    ex = s.expand(sum(Y**n / s.factorial(n) for n in range(a + b + 1)))
    c = s.Poly(ex, w, dl).coeff_monomial(w**a * dl**b)
    return s.Poly(s.expand(c * s.factorial(a) * s.factorial(b)), L)


def int_rn_logj(n, j):
    """int_eps^1 r^n log^j r dr  ->  {(p, k): Fraction}  as  sum c eps^p l^k (l = log eps)."""
    out = {}
    def add(p, k, c):
        if c:
            out[(p, k)] = out.get((p, k), Fraction(0)) + c
    if n == -1:
        add(0, j + 1, Fraction(-1, j + 1))
        return out
    m = n + 1
    # antiderivative r^m sum_i (-1)^i j!/(j-i)! log^{j-i} r / m^{i+1}
    add(0, 0, Fraction((-1)**j * factorial(j), m**(j + 1)))                 # upper limit r=1
    for i in range(j + 1):
        add(m, j - i, -Fraction((-1)**i * factorial(j), factorial(j - i) * m**(i + 1)))
    return out


def moment(weight_terms, ins):
    """sum over weight_terms {n: coeff} of int_eps^1 coeff r^n * ins(L) dr."""
    tot = {}
    for (jj,), cL in ins.terms():
        for n, cw in weight_terms.items():
            for key, c in int_rn_logj(n, jj).items():
                tot[key] = tot.get(key, Fraction(0)) + Fraction(int(cL.p), int(cL.q)) * cw * c
    return {k: v for k, v in tot.items() if v != 0}


def main():
    # check of the build_spec.py insertion table for n = 2 (S_j = q1 q2 log^j r = -L^j)
    S1, S2, S3 = -L, -L**2, -L**3
    table = {'base': 1, 'v': 2 * S1, 'vv': 4 * S1**2, 'vvv': 8 * S1**3, 'd': S2, 'vd': S2 + 2 * S1 * S2,
             'vvd': 4 * S1 * S2 + 4 * S1**2 * S2, 'dd': S2**2 + s.Rational(2, 3) * S3,
             'vdd': s.Rational(2, 3) * S3 + 2 * S2**2 + s.Rational(4, 3) * S1 * S3 + 2 * S1 * S2**2}
    res = {'note': 'ARCHIVE-FREE exact expansions [eps^p l^k] (l = log eps) of the two-kink raw atoms at '
                   '(v,delta)=(1,0); every coefficient not listed is exactly zero. Generated by scripts/two_kink_exact.py.',
           'insertion_table_check_n2': {}, 'atoms': {}}
    for der, (a, b) in DERS.items():
        ins = insertion(a, b)
        res['insertion_table_check_n2'][der] = s.expand(ins.as_expr() - table[der]) == 0
        for name, weight in (('Z2', {-2: Fraction(1), -1: Fraction(-1)}),     # (1-r) r^-2
                             ('Q2', {-1: Fraction(1), 0: Fraction(-1)})):     # (1-r) r^-1
            co = moment(weight, ins)
            atom = f'{name}_{der}'
            res['atoms'][atom] = {str(p): {str(k): str(co[(p, k)]) for k in sorted(k_ for (p_, k_) in co if p_ == p)}
                                  for p in sorted({p_ for (p_, _) in co})}
    assert all(res['insertion_table_check_n2'].values()), res['insertion_table_check_n2']
    # the note's elementary values (l.388): Z2 = 1/eps + l - 1, Q2 = -l - 1 + eps
    assert res['atoms']['Z2_base'] == {'-1': {'0': '1'}, '0': {'0': '-1', '1': '1'}}, res['atoms']['Z2_base']
    assert res['atoms']['Q2_base'] == {'0': {'0': '-1', '1': '-1'}, '1': {'0': '1'}}, res['atoms']['Q2_base']
    # supports: Z2 in {-1,0}, Q2 in {0,1} (used as structural zeros by the assembler)
    for atom, d in res['atoms'].items():
        sup = {int(p) for p in d}
        assert sup <= ({-1, 0} if atom.startswith('Z2') else {0, 1}), (atom, sup)
    res['checks'] = {'insertion_table_n2_matches': True, 'note_l388_Z2_Q2': True, 'supports_Z2_-1_0_Q2_0_1': True}
    json.dump(res, open(OUT / 'two_kink_exact.json', 'w'), indent=1)
    print('two-kink exact atoms:', len(res['atoms']), 'checks', res['checks'])


if __name__ == '__main__':
    main()
