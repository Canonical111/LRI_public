#!/usr/bin/env python3
"""
Cross-check: the jet-arithmetic implementation in lri_framework.py versus the explicit
sympy formulas generated by derive_rg.py / derive_invariants.py, on random inputs.

  1. normalized level: random values for every normalized coefficient that appears in
     out/beta_input_formulas.json (K2=Q2 and C1=A1 from the exact internal sector);
     compare all beta inputs (D4 and C8 sets).
  2. beta level: random beta inputs -> invariants vs out/invariant_formulas.json.
  3. error propagation: gradient of a beta input vs finite differences.
"""
import json
import os
import random
import re
import sys

import mpmath as mp
import sympy as sp

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
import lri_framework as L  # noqa: E402

mp.mp.dps = 40
random.seed(7)


def sym2norm(s):
    # C3_1_vvd -> C3_vvd[l^1] ; K2_0_vE -> K2_vE[l^0]
    m = re.match(r"^([CK]\d)_([01])(?:_([vdE]+))?$", s)
    X, k, ds = m.group(1), m.group(2), m.group(3) or ""
    return f"{X}{'_' + ds if ds else ''}[l^{k}]"


def main():
    ok = True
    formulas = json.load(open(os.path.join(ROOT, "out", "beta_input_formulas.json")))
    for order in ("D4", "C8"):
        fw = L.Framework(order, dps=40)
        names = fw.beta_names
        syms = set()
        for nm in names:
            syms |= set(re.findall(r"[CK]\d_[01](?:_[vdE]+)?", formulas[nm]))
        norm = {}
        subs = {}
        for s in sorted(syms):
            nn = sym2norm(s)
            if nn.startswith("K2") or nn.startswith("C1"):
                # internal exact values (derivative convention)
                m_ = L.NORM_RE.match(nn)
                i, j, e = L.parse_deriv(m_.group(3))
                k = int(m_.group(4))
                if nn.startswith("K2"):
                    t = L.two_kink("Q", i, j, e, 6, None, 40).get((0, k), mp.mpf(0))
                else:
                    t = L.A1_taylor(j, e) if (i == 0 and k == 0) else mp.mpf(0)
                val = t * mp.factorial(i) * mp.factorial(j)
                subs[sp.Symbol(s)] = sp.Float(mp.nstr(val, 40), 40)
                continue
            x = mp.mpf(random.uniform(-3, 3))
            norm[nn] = x
            subs[sp.Symbol(s)] = sp.Float(mp.nstr(x, 40), 40)
        res = fw.from_normalized(norm)
        worst = 0
        for nm in names:
            ex = sp.sympify(formulas[nm])
            ref = mp.mpf(str(sp.N(ex.subs(subs), 40)))
            got = res.beta[nm]
            if got.is_missing:
                print(f"  [{order}] {nm}: MISSING {sorted(got.miss)[:3]}")
                ok = False
                continue
            d = abs(got.v - ref) / (1 + abs(ref))
            worst = max(worst, d)
        print(f"[{order}] beta inputs: jets vs sympy formulas, worst rel. diff = {mp.nstr(worst, 3)}")
        ok &= worst < mp.mpf(10) ** -30
    # ---- invariants ----
    inv = json.load(open(os.path.join(ROOT, "out", "invariant_formulas.json")))
    fw = L.Framework("C8", dps=40)
    beta = {nm: mp.mpf(random.uniform(-5, 5)) for nm in fw.beta_names}
    res = fw.from_beta(beta)
    subs = {sp.Symbol(k): sp.Float(mp.nstr(v, 40), 40) for k, v in beta.items()}
    worst = 0
    for lab in ("D2", "T2", "D3", "T3", "D4", "T4"):
        ref = mp.mpf(str(sp.N(sp.sympify(inv[lab], locals={k: sp.Symbol(k) for k in beta}).subs(subs), 40)))
        got = res.inv[lab].v
        worst = max(worst, abs(got - ref) / (1 + abs(ref)))
    print(f"[C8] invariants: series solver vs sympy formulas, worst rel. diff = {mp.nstr(worst, 3)}")
    ok &= worst < mp.mpf(10) ** -30
    # ---- order bookkeeping: a D4-order run does not produce T4/C8 at all (asking for them is an
    #      error), D4 is available; the C8-order run produces T4 and C8
    fw4 = L.Framework("D4", dps=40)
    r4 = fw4.from_beta({k: v for k, v in beta.items() if k in fw4.beta_names})
    try:
        fw4.required_inputs(outputs=["C8"])
        asked = False
    except ValueError:
        asked = True
    d4ok = ("T4" not in r4.inv and 8 not in r4.C and asked and not r4.inv["D4"].is_missing
            and not res.inv["T4"].is_missing and not res.C[8].is_missing)
    print("[D4] T4/C8 not produced at order D4 (requesting C8 raises):", asked and "T4" not in r4.inv and 8 not in r4.C,
          "| D4 available:", not r4.inv["D4"].is_missing, "| [C8] T4, C8 available:",
          not res.inv["T4"].is_missing and not res.C[8].is_missing)
    ok &= d4ok
    # ---- gradient vs finite difference ----
    fw = L.Framework("D4", dps=40)
    res0 = fw.from_beta(beta)
    h = mp.mpf(10) ** -15
    for inp, out in (("Omega", "D4"), ("K", "D4"), ("N", "T3"), ("a", "D4")):
        b2 = dict(beta)
        b2[inp] += h
        r2 = fw.from_beta({k: v for k, v in b2.items() if k in fw.beta_names})
        fd = (r2.inv[out].v - res0.inv[out].v) / h
        an = res0.inv[out].g.get(inp, 0)
        print(f"  d{out}/d{inp}: forward-mode {mp.nstr(an, 15)}  finite-diff {mp.nstr(fd, 15)}")
        ok &= abs(an - fd) < mp.mpf(10) ** -10
    print("ALL OK" if ok else "FAILURES")
    return ok


if __name__ == "__main__":
    sys.exit(0 if main() else 1)
