#!/usr/bin/env python3
"""C8 extension (phase 3): the raw-moment groups the engine must add for C8 = 8 T4.

Reads the framework agent's C8 requirement files (copied into ../specs/ with their SHA-256, so that the engine's
inputs are frozen):
  specs/framework_required_inputs_C8.json   201 mandatory scalars (derivative convention, 'E' = endpoint source)
  specs/framework_required_inputs_D4.json   116 scalars of order D4 (already delivered by the tier-1 production)
  specs/framework_C8_new_scalars.json       the 85 scalars beyond D4, by new input (W, S, U, J9, L3, M21, M12, N2,
                                            Ndelta, Kv)
  specs/framework_sensitivities_C8.json     signed dC8/dx (exact framework gradients)
Writes specs/production_C8.json (and the collect need file specs/production_C8_need.json): one entry per (moment, derivative) group with the beyond-D4 coefficients only
('coeffs'), the eps powers and jmin of its jobs, the tier of every job and the signed C8 gradient of every
coefficient.  Tier of a job (group, k) = the earliest tier any of its scalars belongs to:
  A: needed by W, S, L3, M21, M12, N2 or Ndelta     (3-6 kinks)
  B: needed by U or Kv (and not by a tier-A input)
  C: needed by J9 only
The D4 (C6/C7) list and specs/production_D4.json are unchanged.
"""
import hashlib, json, os, re, shutil, sys
from math import factorial
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SPEC = os.path.join(ROOT, 'specs')
FW = os.path.join(ROOT, '..', 'framework', 'out')
FILES = {'framework_required_inputs_C8.json': 'required_inputs_C8.json',
         'framework_C8_new_scalars.json': 'C8_new_scalars.json',
         'framework_sensitivities_C8.json': 'sensitivities_C8.json'}
TIER_OF_INPUT = {'W': 'A', 'S': 'A', 'L3': 'A', 'M21': 'A', 'M12': 'A', 'N2': 'A', 'Ndelta': 'A',
                 'U': 'B', 'Kv': 'B', 'J9': 'C'}
NAME_RE = re.compile(r'([AZQ])(\d+)(?:_([vdE]+))?\[eps\^(-?\d+) l\^(\d+)\]')


def sha(p):
    return hashlib.sha256(open(p, 'rb').read()).hexdigest()


def parse(name):
    m = NAME_RE.fullmatch(name)
    if not m:
        raise ValueError(name)
    kind, n, der, p, l = m.group(1), int(m.group(2)), m.group(3) or '', int(m.group(4)), int(m.group(5))
    return f'{kind}{n}_{der or "base"}', kind, n, der, p, l


def main(refresh=False):
    prov = {}
    for dst, src in FILES.items():
        d, s = os.path.join(SPEC, dst), os.path.join(FW, src)
        if refresh or not os.path.exists(d):
            shutil.copyfile(s, d)
        prov[dst] = sha(d)
    req = json.load(open(os.path.join(SPEC, 'framework_required_inputs_C8.json')))['flat_names']
    d4 = set(json.load(open(os.path.join(SPEC, 'framework_required_inputs_D4.json')))['flat_names'])
    new = json.load(open(os.path.join(SPEC, 'framework_C8_new_scalars.json')))
    grad = json.load(open(os.path.join(SPEC, 'framework_sensitivities_C8.json')))['signed']['C8']
    tier_s = {}
    for inp, v in new['by_new_input'].items():
        for s in v['beyond_D4']:
            t = TIER_OF_INPUT[inp]
            tier_s[s] = min(tier_s.get(s, 'C'), t)
    beyond = [s for s in req if s not in d4]
    assert sorted(beyond) == sorted(new['all_beyond_D4']) == sorted(tier_s), 'C8 lists inconsistent'
    groups = {}
    for s in beyond:
        key, kind, n, der, p, l = parse(s)
        if n <= 2:
            continue                     # exact two-kink sector (framework)
        g = groups.setdefault(key, {'kind': kind, 'n': n, 'nv': der.count('v'), 'nd': der.count('d'),
                                    'ne': der.count('E'), 'coeffs': {}, 'tier': {}, 'grad_C8': {}, 'inputs': {}})
        g['coeffs'].setdefault(p, set()).add(l)
        g['tier'][p] = min(g['tier'].get(p, 'C'), tier_s[s])
        g['grad_C8'][f'{p},{l}'] = float(grad.get(s, 0.0))
        g['inputs'][f'{p},{l}'] = sorted(i for i, v in new['by_new_input'].items() if s in v['beyond_D4'])
    out = []
    for key, g in sorted(groups.items(), key=lambda kv: (kv[1]['n'], kv[0])):
        geom = 'full' if g['ne'] else 'angular'
        M = g['n'] + 1 if geom == 'full' else g['n'] - 1
        powers = sorted(g['coeffs'])
        out.append({'name': key, 'kind': g['kind'], 'n': g['n'], 'nv': g['nv'], 'nd': g['nd'], 'ne': g['ne'],
                    'geom': geom, 'dim': M - 1, 'sectors': factorial(M) // 2, 'powers': powers,
                    'jmin': {str(p): min(g['coeffs'][p]) for p in powers},
                    'coeffs': {str(p): sorted(g['coeffs'][p]) for p in powers},
                    'tier': {str(p): g['tier'][p] for p in powers},
                    'grad_C8': g['grad_C8'], 'inputs': g['inputs']})
    doc = {'note': 'C8 extension: raw groups with the coefficients C8 needs BEYOND the order-D4 list (the D4 '
                   'scalars come from the tier-1 production). Generated by py/production_list_C8.py.',
           'provenance_sha256': prov, 'n_groups': len(out),
           'n_scalars': sum(len(v) for o in out for v in o['coeffs'].values()),
           'n_jobs': sum(len(o['powers']) for o in out), 'groups': out}
    json.dump(doc, open(os.path.join(SPEC, 'production_C8.json'), 'w'), indent=1)
    # need file for `campaign.py collect RUN --need specs/production_C8_need.json`: framework_input.json of a C8 run
    # then holds exactly the beyond-D4 scalars (no name shared with the tier-1 production deliverable)
    json.dump([{'name': o['name'], 'coeffs': o['coeffs']} for o in out],
              open(os.path.join(SPEC, 'production_C8_need.json'), 'w'), indent=1)
    print(f"{doc['n_groups']} groups, {doc['n_jobs']} jobs (group, eps power), {doc['n_scalars']} scalars beyond D4")
    for o in out:
        print(f"{o['name']:9s} {o['geom']:7s} d={o['dim']} sec={o['sectors']:6d} "
              + ' '.join(f"k={p}:{o['tier'][p]}{o['coeffs'][p]}" for p in o['coeffs']))


if __name__ == '__main__':
    main(refresh='--refresh' in sys.argv)
