def e(x, d=2):
    if x is None:
        return 'n/a'
    return f'{x:.{d}e}'


def p(x, d=2):
    if x is None:
        return 'n/a'
    return f'{x:+.{d}f}'


def val(s, n=None):
    """decimal string, cut to n significant characters after the point where useful"""
    if n is None:
        return s
    neg = s.startswith('-')
    t = s[1:] if neg else s
    if '.' in t:
        a, b = t.split('.')
        t = a + '.' + b[:max(0, n - len(a))]
    return ('-' if neg else '') + t


def digits_for(sig, value):
    """significant digits to print: up to 2 below the error"""
    if not sig:
        return 22
    v = abs(float(value)) if float(value) != 0 else 1.0
    return max(3, min(22, int(math.floor(math.log10(v))) - int(math.floor(math.log10(sig))) + 3))


def fmt_val(value, sig):
    nd = digits_for(sig, value)
    x = float(value)
    a = abs(x)
    ip = len(str(int(a))) if a >= 1 else 1
    dec = max(0, nd - ip)
    s = value if '.' in value else value
    neg = s.startswith('-')
    t = s[1:] if neg else s
    i, _, fr = t.partition('.')
    return ('-' if neg else '') + i + ('.' + fr[:dec] if dec > 0 else '')


