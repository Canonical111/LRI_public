#!/usr/bin/env python3
"""Check the finite Lagrange formula independently of the root recurrence.

Requires the companion modules and verification/results.json (generated by
verify_new_trials.py). This checks a trial, not a new physical exponent.
"""
from pathlib import Path
import json
from formal_series import s, c, canonical, mul
from spectral_model import evaluate_F

root=Path(__file__).resolve().parents[1]
data=json.loads((root/'verification/results.json').read_text())
coeffs={tuple(k):s.Rational(v) for k,v in data['trial_polynomials']}
v=s.Symbol('v');N=8
# S(t*(2+v),t)/t^2 = (2+v)^2 - 4 + A(t,2+v).
ss=evaluate_F(coeffs,[s.Integer(0),2+v]+[s.Integer(0)]*(N-2),N)
A=ss[2:];A[0]=s.expand(A[0]-((2+v)**2-4))
assert A[0]==0
report={'scope':'Formal Lagrange coefficient identity for the specified fitted trial.','checks':[]}
for n in range(2,7):
    pp=[s.Integer(1)]+[s.Integer(0)]*(n-1)
    acc=0
    for k in range(1,n):
        pp=mul(pp,A,n)
        term=pp[n-1]/(4+v)**k
        vk=s.diff(term,v,k-1).subs(v,0)/s.factorial(k-1)
        acc+=-s.Rational((-1)**k,k)*vk
    value=canonical(acc)
    assert canonical(value-c[n])==0
    report['checks'].append({'n':n,'residual':'0'})
    print('Finite Lagrange formula, n=%d: exact zero'%n,flush=True)
(root/'verification/lagrange_check.json').write_text(json.dumps(report,indent=2)+'\n')
